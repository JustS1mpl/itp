def code_metrics():
    return ts('Метрики качества', [
        task('Точное совпадение. На вход подаются строки «ОТВЕТ МОДЕЛИ|ЭТАЛОН», последняя — «конец». Сравни ответы после нормализации: нижний '
             'регистр, ё → е, только буквы, цифры и пробелы, пробелы между словами одиночные. Для каждой пары выведи «N: ✓» или «N: ✗ (ОТВЕТ ≠ ЭТАЛОН)» '
             'с исходными строками. В конце — «Accuracy: P%» (целые проценты, round).',
             'Нормализация: "".join(ch for ch in text if ch.isalnum() or ch == " "), потом " ".join(text.split()).',
             NORM + '\n\nn = right = 0\nwhile True:\n    line = input()\n    if line == "конец":\n        break\n    n += 1\n    answer, gold = line.split("|")\n'
             '    if norm(answer) == norm(gold):\n        right += 1\n        print(f"{n}: ✓")\n    else:\n        print(f"{n}: ✗ ({answer} ≠ {gold})")\n'
             'print(f"Accuracy: {round(right * 100 / n)}%")',
             ['Париж.|париж\nСтолица — Берлин|Берлин\n  Ёж |еж\n1991 год!|1991 год\nконец', 'Да|да\nконец', 'Нет|Да\nНе знаю|Да\nДа!|Да\nконец']),
        task('Precision и recall. Первая строка — класс, который считаем (например, спам). Дальше строки «ПРЕДСКАЗАНИЕ ЭТАЛОН» через пробел, последняя — '
             '«конец». Выведи «TP=… FP=… FN=…», затем «Precision: P», «Recall: R», «F1: F» с двумя цифрами после точки. Если знаменатель равен '
             'нулю, метрика равна 0.',
             'Сначала посчитай TP, FP, FN циклом; потом каждую метрику — через условное выражение: tp / (tp + fp) if tp + fp else 0.',
             'cls = input()\ntp = fp = fn = 0\nwhile True:\n    line = input()\n    if line == "конец":\n        break\n    p, t = line.split()\n'
             '    if p == cls and t == cls:\n        tp += 1\n    elif p == cls:\n        fp += 1\n    elif t == cls:\n        fn += 1\n'
             'precision = tp / (tp + fp) if tp + fp else 0\nrecall = tp / (tp + fn) if tp + fn else 0\nf1 = 2 * precision * recall / (precision + recall) if precision + recall else 0\n'
             'print(f"TP={tp} FP={fp} FN={fn}")\nprint(f"Precision: {precision:.2f}")\nprint(f"Recall: {recall:.2f}")\nprint(f"F1: {f1:.2f}")',
             ['спам\nспам спам\nнорм спам\nспам норм\nнорм норм\nспам спам\nконец', 'токсично\nнорм норм\nнорм токсично\nнорм норм\nконец',
              'кот\nкот кот\nкот кот\nсобака кот\nконец']),
        task('Кого с кем путают. Дальше строки «ЭТАЛОН ПРЕДСКАЗАНИЕ», последняя — «конец». Выведи «Верно: K из N», затем ошибки — пары, где эталон '
             'и предсказание различаются, — строками «ЭТАЛОН → ПРЕДСКАЗАНИЕ: число» по убыванию числа (при равенстве — по алфавиту пары). Если '
             'ошибок нет — «Ошибок нет».',
             'Counter пар (эталон, предсказание) для ошибок; сортировка: key=lambda p: (-p[1], p[0]).',
             'from collections import Counter\n\nmistakes = Counter()\nn = right = 0\nwhile True:\n    line = input()\n    if line == "конец":\n        break\n'
             '    t, p = line.split()\n    n += 1\n    if t == p:\n        right += 1\n    else:\n        mistakes[(t, p)] += 1\nprint(f"Верно: {right} из {n}")\n'
             'for (t, p), k in sorted(mistakes.items(), key=lambda x: (-x[1], x[0])):\n    print(f"{t} → {p}: {k}")\nif not mistakes:\n    print("Ошибок нет")',
             ['кот кот\nлиса собака\nсобака собака\nлиса собака\nкот лиса\nлиса лиса\nконец', 'да да\nнет нет\nконец',
              'a b\nb a\nb a\nc a\nконец']),
    ])


def th_judge():
    terms = [
        ('рубрика', 'Список критериев с баллами для оценки ответа: «верен ли факт — 0–2, полнота — 0–2, вежливость — 0–1». С рубрикой оценки '
                    'разных людей и моделей сравнимы.'),
        ('LLM-судья', 'Модель, которая оценивает ответы другой модели по рубрике. Быстро и дёшево, но у судьи есть перекосы: любит длинные '
                      'ответы и свой стиль. Его выборочно проверяют люди.'),
        ('регрессия', 'Ухудшение: после изменения то, что раньше работало, сломалось. Новую версию промпта сравнивают со старой на тех же вопросах.'),
    ]
    body = (
        '<p>Не у всех вопросов один правильный ответ: «объясни, как работает цикл» можно сказать по-разному. Тогда ответ проверяют '
        'правилами — есть ли обязательные факты, нет ли запрещённого, не слишком ли длинно:</p>'
        + ex('def check(answer, must, banned, max_words):\n    low = answer.lower()\n    problems = [f"нет «{w}»" for w in must if w not in low]\n'
             '    problems += [f"есть «{w}»" for w in banned if w in low]\n    if len(answer.split()) > max_words:\n        problems.append("длинно")\n    return problems\n\n\n'
             'answer = "Цикл for повторяет тело для каждого элемента. Наверное."\nprint(check(answer, ["for", "элемент", "range"], ["наверное"], 20) or "ок")') +
        '<p>Что правилами не поймать — смысл, логику, тон, — оценивает человек или [[LLM-судья]] по [[рубрика|рубрике]]. Судье дают вопрос, ответ '
        'и критерии и просят вернуть баллы JSON-ом. Перекосы судьи известны: он завышает длинные ответы и ответы в своём стиле, поэтому '
        'часть оценок перепроверяют люди, а в рубрике пишут «длина не влияет на балл».</p>'
        '<h3>Сравнение версий</h3>'
        '<p>Поменял промпт — прогони тот же набор на старой и новой версии. Среднее может вырасти, а отдельные вопросы — упасть: это '
        '[[регрессия]], и её ищут по каждому вопросу отдельно:</p>'
        + ex('old = {"цикл": 5, "словарь": 4, "срез": 4, "функция": 3}\nnew = {"цикл": 5, "словарь": 5, "срез": 2, "функция": 5}\n'
             'print("среднее:", sum(old.values()) / len(old), "→", sum(new.values()) / len(new))\n'
             'print("хуже стало:", [k for k in old if new[k] < old[k]])') +
        '<p>Среднее выросло с 4.0 до 4.25, но «срез» сломался. Выпускать такую версию, не разобравшись, нельзя.</p>'
    )
    return th('Судья и сравнение версий', terms, body)


