from dsl import *

# Нора после «Модуль itertools и collections»: как проверять ответы ИИ. Две теории: метрики на эталонном наборе (нормализация,
# точное совпадение, accuracy, precision/recall/F1, матрица ошибок); проверка правилами, рубрика и LLM-судья, сравнение версий
# и регрессии. Ответы моделей даны строками — сервер не нужен. Мини-проект — экзамен для бота поддержки.

NORM = ('def norm(text):\n    text = text.lower().replace("ё", "е")\n    text = "".join(ch for ch in text if ch.isalnum() or ch == " ")\n'
        '    return " ".join(text.split())\n')


def th_metrics():
    terms = [
        ('эталонный набор', 'Список вопросов с заранее известными правильными ответами (golden set). На нём модель проверяют после каждого '
                            'изменения — как тестами проверяют код.'),
        ('нормализация', 'Приведение ответа к единому виду перед сравнением: нижний регистр, без знаков препинания и лишних пробелов. '
                         '«Париж.» и «париж» — один ответ.'),
        ('accuracy', 'Доля правильных ответов: верных / всех. Простая, но обманчивая метрика, если одних ответов гораздо больше, чем других.'),
        ('precision', 'Точность для класса: из всего, что модель назвала «спамом», какая доля действительно спам. TP / (TP + FP).'),
        ('recall', 'Полнота для класса: из всего настоящего спама какую долю модель нашла. TP / (TP + FN).'),
        ('F1', 'Одно число из precision и recall: 2·P·R / (P + R). Высокое, только если высоки обе.'),
        ('матрица ошибок', 'Таблица «правильный ответ × ответ модели»: сколько раз модель путала один класс с другим.'),
    ]
    body = (
        '<p>«Вроде отвечает нормально» — не оценка. Модель проверяют как код: на [[эталонный набор]] вопросов с известными ответами, '
        'после каждого изменения промпта или модели. Сравнивают не строки как есть, а после [[нормализация|нормализации]]:</p>'
        + ex(NORM + '\n\npairs = [("Париж.", "париж"), ("  Москва  ", "Москва"), ("Ёлка", "елка"), ("Лондон", "Париж")]\n'
             'right = sum(norm(a) == norm(b) for a, b in pairs)\nprint(f"accuracy = {right}/{len(pairs)} = {right / len(pairs):.2f}")') +
        '<p>[[accuracy]] обманывает, когда классы неравны. Пусть из 100 писем 5 — спам. Модель, которая всегда говорит «не спам», '
        'получит accuracy 0.95 и не поймает ни одного спама. Поэтому для важного класса считают [[precision]] и [[recall]]:</p>'
        '<ul><li>TP — назвала спамом, и это спам;</li><li>FP — назвала спамом, а это нормальное письмо (ложная тревога);</li>'
        '<li>FN — пропустила спам.</li></ul>'
        + ex('pred = ["спам", "норм", "спам", "норм", "норм", "спам"]\ntrue = ["спам", "спам", "норм", "норм", "норм", "спам"]\n'
             'tp = sum(p == "спам" and t == "спам" for p, t in zip(pred, true))\nfp = sum(p == "спам" and t != "спам" for p, t in zip(pred, true))\n'
             'fn = sum(p != "спам" and t == "спам" for p, t in zip(pred, true))\nprecision, recall = tp / (tp + fp), tp / (tp + fn)\n'
             'print(tp, fp, fn)\nprint(f"P={precision:.2f} R={recall:.2f} F1={2 * precision * recall / (precision + recall):.2f}")') +
        '<p>Что важнее, решает задача: фильтру спама страшнее ложная тревога (потеряется нужное письмо) — нужен высокий precision; '
        'поиску опасных сообщений страшнее пропуск — нужен recall. [[F1]] сводит их в одно число.</p>'
        '<p>Когда классов много, видно, кого с кем путают, по [[матрица ошибок|матрице ошибок]] — это просто Counter пар:</p>'
        + ex('from collections import Counter\n\ntrue = ["кот", "кот", "собака", "лиса", "собака", "лиса"]\npred = ["кот", "собака", "собака", "собака", "собака", "лиса"]\n'
             'matrix = Counter(zip(true, pred))\nfor (t, p), k in sorted(matrix.items()):\n    print(f"{t} → {p}: {k}")') +
        '<p>Одна тонкость: если подбирать промпт, глядя на один и тот же набор, модель «подгоняется» под него. Поэтому часть вопросов '
        'держат отдельно и проверяют на них только в конце.</p>'
    )
    return th('Метрики качества', terms, body)


