def img(i, alt):
    return '<figure class="exf"><img class="exi" data-x="%s" alt="%s"></figure>' % (i, E(alt, quote=True))


def tab(head, rows):
    h = '<table><tr>' + ''.join('<th>%s</th>' % E(x) for x in head) + '</tr>'
    for r in rows:
        h += '<tr>' + ''.join('<td>%s</td>' % x for x in r) + '</tr>'
    return h + '</table>'


