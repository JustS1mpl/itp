def rpn_ref(tokens):
    st = []
    for t in tokens:
        if t == '+':
            b = st.pop(); a = st.pop(); st.append(a + b)
        elif t == '-':
            b = st.pop(); a = st.pop(); st.append(a - b)
        elif t == '*':
            b = st.pop(); a = st.pop(); st.append(a * b)
        elif t == '/':
            b = st.pop(); a = st.pop(); st.append(a // b)
        elif t == '~':
            st.append(-st.pop())
        elif t == '!':
            n = st.pop(); f = 1
            for i in range(2, n + 1):
                f *= i
            st.append(f)
        elif t == '#':
            x = st.pop(); st.append(x); st.append(x)
        elif t == '@':
            c = st.pop(); b = st.pop(); a = st.pop(); st += [b, c, a]
        else:
            st.append(int(t))
    assert len(st) == 1
    return st[0]


def gen_rpn(seed, length):
    rnd = random.Random(seed)
    toks, st = [], []
    for _ in range(length):
        ops = ['num', 'num']
        if len(st) >= 1:
            ops += ['~', '#']
            if 0 <= st[-1] <= 7:
                ops.append('!')
        if len(st) >= 2:
            ops += ['+', '-', '*']
            if st[-1] != 0:
                ops.append('/')
        if len(st) >= 3:
            ops.append('@')
        op = rnd.choice(ops)
        if op == 'num':
            v = rnd.randint(1, 20)
            toks.append(str(v)); st.append(v)
        else:
            toks.append(op)
            if op == '~':
                st.append(-st.pop())
            elif op == '!':
                n = st.pop(); f = 1
                for i in range(2, n + 1):
                    f *= i
                st.append(f)
            elif op == '#':
                st.append(st[-1])
            elif op == '@':
                c = st.pop(); b = st.pop(); a = st.pop(); st += [b, c, a]
            else:
                b = st.pop(); a = st.pop()
                st.append({'+': a + b, '-': a - b, '*': a * b, '/': a // b if b else 0}[op])
        if st and abs(st[-1]) > 10 ** 9:
            return None
    while len(st) > 1:
        op = rnd.choice(['+', '-'])
        b = st.pop(); a = st.pop()
        st.append(a + b if op == '+' else a - b)
        toks.append(op)
    return ' '.join(toks)


