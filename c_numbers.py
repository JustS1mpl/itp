def th_divmod():
    terms = [
        ('//',
         'Целочисленное деление: делит и округляет вниз, к меньшему целому. Для положительных чисел — просто отбрасывает '
         'дробную часть.\n'
         'Пример:\nprint(17 // 5)\nprint(-7 // 2)\nВывод:\n3\n-4'),
        ('%',
         'Остаток от деления. Если остаток 0 — число делится нацело; n % 10 — последняя цифра числа.\n'
         'Пример:\nprint(17 % 5)\nprint(2048 % 10)\nВывод:\n2\n8'),
        ('ZeroDivisionError',
         'Ошибка деления на ноль — при /, // и % на 0.\n'
         'Текст: division by zero; для // и % — integer division or modulo by zero.'),
    ]
    body = (
        '<p>Часто нужно делить нацело: «17 конфет на 5 человек — по 3 и 2 в остатке». '
        'Для этого есть [[//]] — сколько раз второе число целиком помещается в первом — и [[%]] — что осталось:</p>'
        + ex('print(17 // 5)\nprint(17 % 5)') +
        '<p>Это пара для перевода единиц. В часе 60 минут:</p>'
        + ex('minutes = int(input("Минут: "))\nprint(f"{minutes // 60} ч {minutes % 60} мин")', ['137']) +
        '<h3>Цифры числа</h3>'
        '<p>С делением на 10 число разбирают на цифры: <code>% 10</code> — последняя цифра, <code>// 10</code> — '
        'число без неё, <code>// 100</code> отрезает две цифры, <code>% 100</code> оставляет две последние. '
        'Обратно число собирают по разрядам:</p>'
        + ex('n = 2048\nprint(n % 10, n // 10, n // 10 % 10, n // 1000)\ntens = 4\nones = 7\nprint(tens * 10 + ones)') +
        '<p><code>//</code> и <code>%</code> стоят в одном ряду с <code>*</code> и <code>/</code> и выполняются слева направо: '
        '<code>n // 10 % 10</code> — сначала 204, потом его последняя цифра.</p>'
        '<p>Остаток от деления на 2 показывает чётность: у чётных он 0, у нечётных 1. Для отрицательных чисел '
        '<code>//</code> округляет вниз, к меньшему: <code>-7 // 2</code> даёт -4.</p>'
        '<h3>Деление на ноль</h3>'
        + exerr('people = 0\nprint(100 / people)') +
        '<p>[[ZeroDivisionError]] — то же будет и с <code>//</code>, и с <code>%</code>.</p>'
    )
    return th('Целое деление и остаток', terms, body)


