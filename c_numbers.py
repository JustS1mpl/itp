def th_round():
    terms = [
        ('round',
         'round(x) — округляет число x до целого. round(x, n) — до n знаков после точки.\n'
         'Пример:\nprint(round(3.7))\nprint(round(3.14159, 2))\nВывод:\n4\n3.14\n'
         'Если число ровно посередине (2.5, 3.5), round округляет к ближайшему чётному: round(2.5) даёт 2, round(3.5) даёт 4.'),
        ('abs',
         'abs(x) — модуль числа: то же число без знака минус.\n'
         'Пример:\nprint(abs(-8))\nprint(abs(8))\nВывод:\n8\n8'),
        ('min',
         'min(a, b, ...) — возвращает самое маленькое из переданных значений.\n'
         'Пример:\nprint(min(7, 2, 9))\nВывод:\n2'),
        ('max',
         'max(a, b, ...) — возвращает самое большое из переданных значений.\n'
         'Пример:\nprint(max(7, 2, 9))\nВывод:\n9'),
    ]
    body = (
        '<p>В Python есть готовые функции для частых вычислений.</p>'
        '<h3>round — округление</h3>'
        '<p>[[round]] с одним аргументом округляет до целого, со вторым аргументом — до нужного числа знаков после точки:</p>'
        + ex('print(round(7.6))\nprint(round(7.4))\nprint(round(0.1 + 0.2, 2))\nprint(round(2 / 3, 3))') +
        '<p>Так решается проблема с «лишними» цифрами: <code>round(0.1 + 0.2, 2)</code> даёт 0.3.</p>'
        '<p>Нули в конце дробной части Python не пишет. Если округлить до двух знаков число, у которого '
        'после точки одна цифра, она одна и останется:</p>'
        + ex('print(round(4.5, 2))\nprint(round(5.0, 2))\nprint(round(7.123, 2))') +
        '<p>Поэтому в задачах «округли до двух знаков» правильный ответ может выглядеть как 4.5 или 5.0 — это нормально. '
        'Как вывести ровно два знака, 4.50, узнаешь в теме «Оформление вывода».</p>'
        '<p>Одна особенность: если число ровно посередине между двумя целыми, <code>round</code> выбирает чётное:</p>'
        + ex('print(round(2.5))\nprint(round(3.5))') +
        '<h3>round и int</h3>'
        '<p>Не путай <code>round</code> с <code>int</code>: <code>int</code> от дробного числа не округляет, '
        'а просто отбрасывает дробную часть:</p>'
        + ex('print(int(7.9))\nprint(round(7.9))') +
        '<p>Помнишь, <code>int("2.5")</code> давал ValueError? Из <b>строки</b> с дробной записью <code>int</code> '
        'число не делает. А из уже готового дробного <b>числа</b> 7.9 — делает, отбросив дробную часть.</p>' +
        '<h3>abs — модуль</h3>'
        '<p>[[abs]] убирает знак минус. Удобно, когда важна разница, а не направление:</p>'
        + ex('t_morning = -6\nt_day = 4\nprint(abs(t_morning - t_day))') +
        '<p>Разница температур — 10 градусов, неважно, в какую сторону.</p>'
        '<h3>min и max</h3>'
        '<p>[[min]] возвращает самое маленькое из значений, [[max]] — самое большое. Значений может быть сколько угодно:</p>'
        + ex('print(min(12, 5, 8))\nprint(max(12, 5, 8))\nprint(max(-3, -10))') +
    '')
    return th('Округление, модуль, минимум и максимум', terms, body)


