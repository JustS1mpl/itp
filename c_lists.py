def th_split():
    terms = [
        ('split',
         'Метод строки: разбивает её на список частей. Без аргумента — по пробелам (сколько бы их ни было), '
         'с аргументом — по указанной строке.\n'
         'Пример:\nprint("a b  c".split())\nprint("1,2,3".split(","))\nВывод:\n[\'a\', \'b\', \'c\']\n[\'1\', \'2\', \'3\']'),
        ('join',
         'Метод строки-разделителя: склеивает список строк в одну строку. Все элементы должны быть строками.\n'
         'Пример:\nprint(" - ".join(["a", "b", "c"]))\nВывод:\na - b - c'),
        ('map',
         'map(функция, список) применяет функцию к каждому элементу. Готовый приём для чтения чисел в одной строке: '
         'list(map(int, input().split())). Подробно map разберём в теме «Гибкие функции».\n'
         'Пример:\nnums = list(map(int, "3 10 7".split()))\nprint(nums, sum(nums))\nВывод:\n[3, 10, 7] 20'),
    ]
    body = (
        '<h3>Строку — в список: split</h3>'
        '<p>Часто данные приходят одной строкой: «5 12 8» или «Ира,Тимур,Ли». Метод [[split]] разбивает строку на список частей — '
        'без аргумента по пробелам, с аргументом по указанному разделителю:</p>'
        + ex('line = "Ира Тимур  Ли"\nprint(line.split())\ncsv = "яблоки,груши,сливы"\nprint(csv.split(","))') +
        '<h3>Список — в строку: join</h3>'
        '<p>Обратное действие — [[join]]. Его вызывают у строки-разделителя и передают список строк:</p>'
        + ex('words = ["мама", "мыла", "раму"]\nprint(" ".join(words))\nprint("-".join(words))\nprint("".join(["a", "b", "c"]))') +
        '<p>Элементы должны быть строками: <code>" ".join([1, 2])</code> даст TypeError.</p>'
        '<h3>Числа в одной строке</h3>'
        '<p>После <code>split</code> получаются строки, а для расчётов нужны числа. Каждую можно превратить в цикле, '
        'но есть готовый приём — [[map]]: он применяет функцию <code>int</code> к каждому элементу, а <code>list</code> '
        'собирает результат в список. Пока используй его как готовую формулу:</p>'
        + ex('nums = list(map(int, input("Числа: ").split()))\nprint(nums)\nprint("Сумма:", sum(nums), "среднее:", sum(nums) / len(nums))', ['4 8 15 16 23 42']) +
        '<p>Как устроен <code>map</code> и что ещё он умеет, разберём в теме «Гибкие функции».</p>'
    )
    return th('Строки и списки', terms, body)


