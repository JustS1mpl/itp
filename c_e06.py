def cmd(c):
    return 'Поднять хвост' if c[0] == 'up' else 'Опустить хвост' if c[0] == 'down' else '%s %s' % (CN[c[0]], c[1])


def prog_text(Q):
    if Q['kind'] == 'D':
        return 'Повтори %d раз\n' % Q['k'] + '\n'.join('    Сместиться на (%d, %d)' % tuple(m) for m in Q['moves']) + '\nКонец'
    o, cur = [], []
    for c in Q['prog']:
        if c[0] == 'rep':
            if cur: o.append(' '.join(cur)); cur = []
            o.append('Повтори %d [%s]' % (c[1], ' '.join(cmd(x) for x in c[2])))
        else:
            cur.append(cmd(c))
    if cur: o.append(' '.join(cur))
    return '\n'.join(o)


