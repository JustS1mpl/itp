def th_continue():
    terms = [
        ('continue',
         'Пропускает остаток блока и сразу переходит к следующей итерации цикла.\n'
         'Пример:\nfor i in range(5):\n    if i == 2:\n        continue\n    print(i, end="")\nВывод:\n0134'),
        ('pass',
         'Пустая команда: ничего не делает. Нужна там, где Python требует блок с отступом, а писать в нём пока нечего, — '
         'в теле цикла, в ветке if, позже — в функции и классе. В отличие от continue, не прерывает итерацию: '
         'код после pass выполняется как обычно.\n'
         'Пример:\nfor i in range(3):\n    if i == 1:\n        pass\n    print(i, end="")\nВывод:\n012'),
    ]
    body = (
        '<h3>continue — пропустить итерацию</h3>'
        '<p>[[continue]] прерывает текущую итерацию и сразу переходит к следующей — в отличие от <code>break</code>, '
        'который заканчивает весь цикл:</p>'
        + ex('for i in range(1, 11):\n    if i % 3 == 0:\n        continue\n    print(i, end=" ")') +
        '<p>Числа, кратные трём, пропущены. Такой код можно написать и через <code>if</code> с обратным условием — '
        '<code>continue</code> удобен, когда «неподходящих» случаев несколько и их хочется отсеять в начале блока.</p>'
        '<h3>pass — пустой блок</h3>'
        '<p>После <code>for</code>, <code>while</code> и <code>if</code> Python требует хотя бы одну команду с отступом. '
        'Если программа ещё пишется и блок оставлен на потом, ставят [[pass]] — команду, которая ничего не делает. '
        'Не путай с <code>continue</code>: <code>pass</code> итерацию не прерывает.</p>'
        + ex('for i in range(1, 6):\n    if i % 2 == 0:\n        pass  # чётные обработаем потом\n    else:\n        print(i, end=" ")\n'
             'print()\nfor i in range(1, 6):\n    if i == 3:\n        pass\n    print(i, end=" ")') +
        '<p>Во втором цикле тройка напечаталась: <code>pass</code> на ход цикла не влияет. С пустым блоком без '
        '<code>pass</code> программа не запустится — будет <code>IndentationError</code>, Python ждёт отступ.</p>'
        '<h3>Флаг</h3>'
        '<p>Чтобы узнать, нашлось ли что-то при переборе, заводят переменную-<b>флаг</b>: до цикла <code>False</code>, '
        'а при находке — <code>True</code>. После цикла проверяют флаг:</p>'
        + ex('nick = input("Ник: ")\nhas_digit = False\nfor c in nick:\n    if c.isdigit():\n        has_digit = True\n        break\n'
             'print("Есть цифра" if has_digit else "Только буквы")', ['kira2010']) +
        '<p><code>break</code> здесь экономит время: если цифра нашлась, дальше искать незачем. '
        'Так же проверяют, простое ли число — делится ли оно хоть на что-то, кроме 1 и себя:</p>'
        + ex('n = int(input("n = "))\nprime = n > 1\nfor d in range(2, n):\n    if n % d == 0:\n        prime = False\n        break\nprint("Простое" if prime else "Составное")', ['97']) +
        '<p>Делители достаточно искать до квадратного корня из n: если делитель больше корня, парный ему меньше корня '
        'и уже был бы найден. Для больших чисел это огромная экономия: <code>range(2, int(n ** 0.5) + 1)</code>.</p>'
    )
    return th('continue и флаг', terms, body)


