def th_for():
    terms = [
        ('for',
         'Цикл перебора: по очереди берёт каждый элемент — число из range или символ строки — и выполняет блок.\n'
         'Пример:\nfor c in "кот":\n    print(c)\nВывод:\nк\nо\nт'),
        ('range',
         'Последовательность целых чисел для перебора. range(n) — от 0 до n-1; range(a, b) — от a до b-1; '
         'range(a, b, шаг) — с шагом, шаг может быть отрицательным. Конец в диапазон не входит.\n'
         'Пример:\nfor i in range(2, 9, 3):\n    print(i)\nВывод:\n2\n5\n8'),
    ]
    body = (
        '<p>Когда заранее известно, что перебирать, удобнее цикл [[for]]: он сам берёт элементы по очереди. '
        'Числа для перебора даёт [[range]]:</p>'
        + ex('for i in range(5):\n    print(i, end=" ")\nprint()\nfor i in range(1, 6):\n    print(i, end=" ")\nprint()\n'
             'for i in range(10, 0, -3):\n    print(i, end=" ")') +
        '<p><code>range(5)</code> — числа от 0 до 4: пять штук, начиная с нуля. <code>range(1, 6)</code> — от 1 до 5: '
        'конец в диапазон не входит. Третий аргумент — шаг, в том числе отрицательный. Переменная <code>i</code> '
        'на каждой итерации получает следующее число; имя может быть любым.</p>'
        '<p>То же на <code>while</code> заняло бы больше строк — счётчик, условие, увеличение. <code>for</code> делает это сам, '
        'поэтому, когда число повторов известно, берут его. Накопители и счётчики работают как раньше:</p>'
        + ex('n = int(input("n = "))\ntotal = 0\nfor i in range(1, n + 1):\n    total += i\nprint(f"1 + ... + {n} = {total}")', ['100']) +
        '<h3>Перебор строки</h3>'
        '<p><code>for</code> умеет перебирать и строку — символ за символом:</p>'
        + ex('word = "программа"\ncount = 0\nfor c in word:\n    if c in "аеёиоуыэюя":\n        count += 1\nprint("Гласных:", count)') +
        '<p>Если нужны и номер, и символ, перебирают индексы: <code>for i in range(len(word))</code>, а символ берут как <code>word[i]</code>.</p>'
    )
    return th('Цикл for и range', terms, body)


