        '<p><code>&gt;10.2f</code> — вправо в поле шириной 10, два знака после точки. Теперь понятно, почему опасно '
        'забыть точку: <code>{price:2f}</code> — это ширина 2 и обычные для f шесть знаков после точки.</p>'
        '<h3>Пробелы в конце строк</h3>'
