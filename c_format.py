         'Знак перед шириной задаёт выравнивание: < — влево, > — вправо, ^ — по центру.\n'
         'Пример:\nprint(f"[{\'да\':<6}]")\nprint(f"[{\'да\':>6}]")\nprint(f"[{\'да\':^6}]")\n'
