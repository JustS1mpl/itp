def th_width():
    terms = [
        ('формат в f-строке',
         'После значения в фигурных скобках f-строки ставят двоеточие и формат — как показать значение.\n'
         '.2f — ровно два знака после точки; 10 — ширина поля; < > ^ — выравнивание. Части сочетаются: {x:>10.2f}.\n'
         'Частая ошибка: {x:2f} без точки — это ширина 2, а не два знака.\n'
         'Пример:\nprice = 4.5\nprint(f"[{price:.2f}] [{price:>7.2f}]")\nВывод:\n[4.50] [   4.50]'),
        ('ширина поля',
         'Число после двоеточия — сколько символов минимум займёт значение. Пустое место — пробелы; '
         'числа по умолчанию прижимаются вправо, строки — влево. Длинное значение не обрезается.\n'
         'Пример:\nprint(f"[{7:5}]")\nprint(f"[{\'ок\':5}]")\nВывод:\n[    7]\n[ок   ]'),
        ('выравнивание',
         '< — влево, > — вправо, ^ — по центру. Пишется перед шириной.\n'
         'Пример:\nprint(f"[{\'да\':<6}]")\nprint(f"[{\'да\':^6}]")\nВывод:\n[да    ]\n[  да  ]'),
    ]
    body = (
        '<p><code>round</code> убирает лишние цифры, но не дописывает нули: 4.5 так и останется 4.5. '
        'Для цен и таблиц нужен точный вид, и его задаёт [[формат в f-строке|формат]]: после значения в фигурных скобках '
        'ставят двоеточие и описывают, как его показать.</p>'
        '<h3>Знаки после точки</h3>'
        + ex('price = 4.5\nx = 2 / 3\nprint(f"Цена: {price:.2f} руб.")\nprint(f"{x:.3f}")\nprint(f"{x:.0f}")\nprint(f"{7:.2f}")') +
        '<p><code>.2f</code> — «дробное число (f) с двумя знаками после точки». Формат округляет как <code>round</code>, '
        'но всегда показывает ровно столько знаков, сколько указано. Сама переменная не меняется — меняется только вид в этой строке, '
        'поэтому считать лучше с полными значениями, а форматировать при выводе.</p>'
        '<h3>Ширина и выравнивание</h3>'
        '<p>Чтобы выстроить вывод столбиками, задают [[ширина поля|ширину поля]] — сколько символов займёт значение, '
        'и [[выравнивание]]: <code>&lt;</code> влево, <code>&gt;</code> вправо, <code>^</code> по центру. '
        'Квадратные скобки в примерах — просто текст, чтобы были видны границы поля:</p>'
        + ex('word = "ИТП"\nprint(f"[{word:<9}]")\nprint(f"[{word:>9}]")\nprint(f"[{word:^9}]")\nprint(f"[{42:6}]")') +
        '<p>Без знака выравнивания числа прижимаются вправо, строки — влево. Ширина — это минимум: длинное значение '
        'не обрежется, а сдвинет всё правее. Если у всех строк одинаковые ширины, получается таблица — в скобках '
        'можно писать и сами значения:</p>'
        + ex('print(f"{\'Город\':<12}{\'Темп.\':>6}")\nprint(f"{\'Мурманск\':<12}{-3:>6}")\nprint(f"{\'Сочи\':<12}{17:>6}")') +
        '<p>Ширина и точность сочетаются — сначала выравнивание, потом ширина, потом точность: '
        '<code>{price:&gt;10.2f}</code>. Отсюда и ловушка: <code>{price:2f}</code> без точки — это ширина 2 и '
        'обычные шесть знаков после точки.</p>'
        '<p>Ширину можно взять из переменной — внутри формата её тоже пишут в фигурных скобках:</p>'
        + ex('w = 11\ntitle = "Рекорды"\nprint("-" * w)\nprint(f"{title:^{w}}")\nprint("-" * w)') +
        '<p>Пробелы справа от прижатого влево или центрированного значения на экране не видны, и в задачах проверка их '
        'не учитывает — только пробелы в начале и середине строк.</p>'
    )
    return th('Знаки после точки и ширина поля', terms, body)


