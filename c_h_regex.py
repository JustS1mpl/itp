def th_groups():
    terms = [
        ('группа', 'Часть шаблона в круглых скобках. Совпадение запоминает, что попало в каждую группу: m.group(1), m.group(2)… '
                   'findall при двух и более группах возвращает кортежи, при одной — просто строки.'),
        ('sub', 're.sub(шаблон, замена, текст) — заменить все совпадения. В замене \\1, \\2 — текст групп.\n'
                'Пример:\nimport re\nprint(re.sub(r"\\s+", " ", "много   пробелов  тут"))\nВывод:\nмного пробелов тут'),
        ('fullmatch', 're.fullmatch(шаблон, текст) — совпадение, только если шаблону соответствует вся строка целиком; иначе None. '
                      'Так проверяют формат ввода.'),
    ]
    body = (
        '<p>Часто нужно не только найти кусок, но и разобрать его на части. Для этого части шаблона берут в скобки — каждая '
        '[[группа]] запоминает свой кусок, а <code>group</code> его достаёт:</p>'
        + ex('import re\n\nm = re.search(r"(\\d{2})\\.(\\d{2})\\.(\\d{4})", "Контрольная 28.10.2026 в 10:00")\nprint(m.group(), m.group(3), m.group(2), m.group(1))\n'
             'print(re.findall(r"(\\w+)=(\\w+)", "user=zed action=pay code=402"))') +
        '<p>Если групп две и больше, findall возвращает список кортежей — из пар удобно сразу сделать словарь. При одной группе — '
        'просто список строк этой группы.</p>'
        '<h3>Замена</h3>'
        '<p>[[sub]] заменяет все совпадения. В строке замены <code>\\1</code>, <code>\\2</code> — текст групп, так можно переставлять части:</p>'
        + ex('import re\n\nprint(re.sub(r"(\\d{2})\\.(\\d{2})\\.(\\d{4})", r"\\3-\\2-\\1", "с 01.09.2026 по 31.05.2027"))\n'
             'print(re.sub(r"\\d", "*", "карта 1234 5678"))') +
        '<h3>Проверка формата</h3>'
        '<p>search найдёт шаблон и посреди мусора. Чтобы проверить, что вся строка соответствует формату, есть [[fullmatch]]:</p>'
        + ex('import re\n\nfor nick in ["zed_2026", "zed 2026", "ab", "Очень_длинный_ник_больше_16"]:\n    ok = re.fullmatch(r"\\w{3,16}", nick)\n'
             '    print(nick, "—", "подходит" if ok else "не подходит")') +
        '<p>Регулярные выражения мощные, но быстро становятся нечитаемыми. Если хватает <code>split</code> или <code>in</code> — лучше они.</p>'
    )
    return th('Группы и замена', terms, body)


