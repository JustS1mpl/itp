def th_pattern():
    terms = [
        ('re', 'Модуль регулярных выражений: поиск в тексте по шаблону. import re.'),
        ('r-строка', 'Строка с буквой r перед кавычками: r"\\d+". Обратная косая черта в ней — обычный символ, а не начало спецсимвола. '
                     'Шаблоны регулярных выражений пишут так, чтобы \\d не превратилось во что-то другое.'),
        ('класс символов', 'Набор символов, любой из которых подходит на одно место: [абв], [0-9], [^0-9] — «не цифра». Готовые: \\d — цифра, '
                           '\\w — буква, цифра или _, \\s — пробельный символ, . — любой символ.'),
        ('квантификатор', 'Сколько раз повторяется то, что слева: + — один и больше, * — ноль и больше, ? — ноль или один, {3} — ровно 3, '
                          '{2,4} — от 2 до 4.'),
        ('findall', 're.findall(шаблон, текст) — список всех найденных кусков.\nПример:\nimport re\nprint(re.findall(r"\\d+", "a1b22c333"))\n'
                    'Вывод:\n[\'1\', \'22\', \'333\']'),
        ('search', 're.search(шаблон, текст) — первое совпадение (объект, у которого .group() — найденный текст) или None.'),
        ('group', 'm.group() — весь найденный текст совпадения, m.group(k) — текст k-й группы (с 1; группы — во второй теории).'),
    ]
    body = (
        '<p>Методы строк ищут точный текст. А как найти «любой номер телефона» или «все хештеги»? Для этого есть регулярные '
        'выражения — маленький язык шаблонов, модуль [[re]]. Шаблоны пишут как [[r-строка]], чтобы обратная косая черта не '
        'превратилась в спецсимвол строки.</p>'
        '<p>Шаблон состоит из обычных символов (они ищутся как есть) и специальных. [[класс символов]] подходит на одно место: '
        '<code>\\d</code> — любая цифра, <code>[абв]</code> — одна из трёх букв. [[квантификатор]] говорит, сколько раз повторить: '
        '<code>\\d+</code> — одна или больше цифр подряд, то есть целое число.</p>'
        + ex('import re\n\ntext = "В 9Б учатся 27 человек, в 9А — 25, кабинет 314."\nprint(re.findall(r"\\d+", text))\nprint(re.findall(r"9[АБ]", text))\n'
             'print(re.findall(r"\\d{3}", text))') +
        '<p>[[findall]] возвращает все найденные куски списком. [[search]] ищет первое совпадение и возвращает объект совпадения '
        'или None — удобно в <code>if</code>:</p>'
        + ex('import re\n\nfor s in ["пиши на zed@mail.ru", "почты нет"]:\n    m = re.search(r"\\w+@\\w+\\.\\w+", s)\n    print(m.group() if m else "не найдено")') +
        '<p>Точка в шаблоне — «любой символ», поэтому настоящую точку пишут как <code>\\.</code>. Якоря <code>^</code> и <code>$</code> '
        'привязывают шаблон к началу и концу строки: <code>^\\d+$</code> — строка целиком из цифр.</p>'
        + ex('import re\n\nprint(re.findall(r"#\\w+", "Лучший день #лето #море! #2026"))\nprint(re.findall(r"[А-ЯЁ][а-яё]+", "Аня и Борис пошли к Вике"))\n'
             'print(bool(re.search(r"^\\d+$", "2026")), bool(re.search(r"^\\d+$", "20 26")))')
    )
    return th('Шаблоны', terms, body)


