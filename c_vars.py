def th_concat():
    terms = [
        ('склейка строк',
         'Знак + между двумя строками склеивает их в одну: вторая строка приписывается к концу первой.\n'
         'Пробел сам не появляется — его нужно добавить в одну из строк.\n'
         'Пример:\nname = "Оля"\nprint("Привет, " + name + "!")\nВывод:\nПривет, Оля!\n'
         'Частая ошибка: склеить строку с числом, например "Мне " + 15. Будет ошибка TypeError.'),
        ('повтор строки',
         'Знак * между строкой и целым числом повторяет строку столько раз, сколько указано.\n'
         'Пример:\nprint("-" * 12)\nprint("ха" * 3)\nВывод:\n------------\nхахаха'),
    ]
    body = (
        '<p>Строки можно соединять знаком <code>+</code>. Это называется [[склейка строк|склейкой]]: '
        'вторая строка приписывается в конец первой.</p>'
        + ex('first = "супер"\nsecond = "сила"\nword = first + second\nprint(word)') +
        '<p>Получилась новая строка «суперсила», и её положили в переменную <code>word</code>. '
        'Обрати внимание: пробел между частями не появился. В отличие от <code>print</code> с запятыми, '
        'знак <code>+</code> ничего не добавляет сам. Пробелы и знаки нужно дописать в строки:</p>'
        + ex('name = input("Имя: ")\nprint("Привет, " + name + "!")', ['Оля']) +
        '<p>Пробел стоит внутри строки "Привет, " — после запятой. А восклицательный знак приклеился сразу после имени, '
        'как и должно быть. С <code>print("Привет,", name, "!")</code> между именем и знаком появился бы лишний пробел.</p>'
        '<h3>Повтор строки</h3>'
        '<p>Строку можно умножить на целое число: она [[повтор строки|повторится]] столько раз. '
        'Так удобно рисовать линии и рамки:</p>'
        + ex('print("=" * 20)\nprint("  Таблица рекордов")\nprint("=" * 20)') +
        '<p>Знак <code>*</code> — звёздочка, на компьютере Shift и 8. Между строкой и целым числом она означает повтор: '
        'здесь строка "=" повторена 20 раз. Что звёздочка делает с двумя числами, узнаем в теме «Числа и вычисления».</p>'
        + ex('cheer = "го" * 3\nprint(cheer + "!")') +
        '<p>Результат повтора — тоже строка, её можно положить в переменную и склеить с другой.</p>'
    )
    return th('Склейка и повтор строк', terms, body)


