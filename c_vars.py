def th_fstr():
    terms = [
        ('f-строка',
         'Строка с буквой f перед кавычками. В фигурных скобках {} внутри неё можно писать переменные и вычисления — '
         'Python подставит их значения. Числа превращать в строки не нужно.\n'
         'Частая ошибка: забыть f — скобки выведутся как есть: {name}.\n'
         'Пример:\nname = "Кира"\nlevel = 7\nprint(f"{name}: уровень {level}, дальше {level + 1}")\n'
         'Вывод:\nКира: уровень 7, дальше 8'),
    ]
    body = (
        '<p>Склеивать текст с переменными через <code>+</code> неудобно: легко забыть пробел, а числа приходится '
        'превращать через <code>str</code>. Удобнее [[f-строка|f-строки]]: перед кавычками ставят букву <code>f</code>, '
        'а переменные пишут прямо в тексте в фигурных скобках:</p>'
        + ex('name = "Кира"\nlevel = 7\nprint(f"{name} на уровне {level}")') +
        '<p>Python подставил значения вместо <code>{name}</code> и <code>{level}</code>, число превратилось в текст само. '
        'В скобках можно и считать:</p>'
        + ex('goals = int(input("Голов в первом тайме: "))\nmore = int(input("Голов во втором тайме: "))\n'
             'print(f"Всего голов: {goals + more}")', ['2', '1']) +
        '<p>Без буквы <code>f</code> строка обычная, и фигурные скобки останутся в выводе как есть:</p>'
        + ex('name = "Кира"\nprint("Привет, {name}!")') +
        '<p>Теперь у тебя три способа вывести текст с данными: запятые в <code>print</code> (между частями всегда '
        'пробел или <code>sep</code>), склейка <code>+</code> (полный контроль, но нужен <code>str</code> для чисел) '
        'и f-строка — обычно самый удобный. В задачах годится любой: проверяется только вывод.</p>'
    )
    return th('f-строки', terms, body)


