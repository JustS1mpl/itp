def qm(text, code, expect, right, wrongs, e, lines=None):
    code = code.strip('\n')
    plain, _ = run(code, lines)
    assert plain.rstrip('\n') == expect, (code, plain)
    FL.append(dict(code=code, lines=lines or [], right=expect))
    t = text
    if lines:
        t += ' Пользователь вводит ' + ('по очереди: ' + ', '.join(lines) if len(lines) > 1 else lines[0]) + '.'
    return q(t, right, wrongs, e, code)


