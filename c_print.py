def th_end():
    terms = [
        ('end',
         'end — именованный аргумент функции print: строка, которую print выводит после всех значений.\n'
         'Если end не указан, это перевод строки, поэтому следующий print начинает с новой строки.\n'
         'Пример:\nprint("Раз", end=" ")\nprint("два")\nВывод:\nРаз два\n'
         'Если указать end, перевода строки после этого print не будет — его нужно добавлять самому, если он нужен.'),
        ('перевод строки',
         'Перевод строки — невидимый символ «дальше с новой строки». В коде его записывают двумя знаками: обратная '
         'косая черта и латинская буква n, \\n. Внутри строки это один символ.\n'
         'Пример:\nprint("Первая\\nВторая")\nВывод:\nПервая\nВторая\n'
         'Обратная косая черта \\ — это не обычная косая /. На компьютере это клавиша над Enter или слева от него '
         '(в английской раскладке), на телефоне — на странице символов.'),
    ]
    body = (
        '<p>Почему каждый <code>print</code> начинает с новой строки? После всех значений <code>print</code> выводит '
        'ещё один невидимый символ — [[перевод строки|перевод строки]]. Он и переносит следующий вывод ниже.</p>'
        '<p>Что выводить в конце, задаёт именованный аргумент [[end]]. Его можно поменять, как <code>sep</code>:</p>'
        + ex('print("Загрузка", end="...")\nprint(" Готово!")') +
        '<p>Первый <code>print</code> вывел «Загрузка», а вместо перевода строки — три точки. '
        'Второй <code>print</code> продолжил ту же строку. Пробел перед «Готово!» стоит внутри строки, '
        'иначе слова слиплись бы с точками.</p>'
        + ex('print("Раз", end=" ")\nprint("два", end=" ")\nprint("три")') +
        '<p>Три команды — одна строка вывода: у первых двух в конце пробел вместо перевода строки.</p>'
        '<h3>Перевод строки внутри текста</h3>'
        '<p>Перевод строки можно вставить и прямо в строку. В коде его пишут двумя знаками: обратная косая черта '
        'и латинская буква n — <code>\\n</code>. Python видит в них один символ «с новой строки»:</p>'
        + ex(r'print("Миссия выполнена\nНаграда: 100 монет\nСледующий уровень: 2")') +
        '<p>Одна команда <code>print</code>, а строк вывода три: каждый <code>\\n</code> начал новую. '
        'Сами знаки <code>\\n</code> на экран не попали.</p>'
        '<p>Именованные аргументы можно сочетать с любыми строками. Например, <code>sep="\\n"</code> выведет каждое значение на своей строке:</p>'
        + ex(r'print("красный", "жёлтый", "зелёный", sep="\n")')
    )
    return th('Перевод строки и end', terms, body)


