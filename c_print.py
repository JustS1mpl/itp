def th_sep():
    terms = [
        ('аргумент',
         'Аргумент — значение, которое передают функции в скобках. Если аргументов несколько, их разделяют запятыми.\n'
         'Пример:\nprint("Счёт", 3)\nВывод:\nСчёт 3\n'
         'Здесь у print два аргумента: строка "Счёт" и число 3.'),
        ('sep',
         'sep — именованный аргумент функции print: строка, которую print ставит между значениями. '
         'Название — от английского separator, «разделитель».\n'
         'Если sep не указан, разделитель — один пробел. Пишется в скобках после всех значений: sep="...".\n'
         'Пример:\nprint(9, 45, sep=":")\nВывод:\n9:45\n'
         'Если нужен вывод слитно, без разделителя, пиши sep="" — две кавычки подряд, между ними ничего.'),
    ]
    body = (
        '<p>В скобках у <code>print</code> можно передать несколько значений через запятую. '
        'Такие значения называются [[аргумент|аргументами]] функции. '
        '<code>print</code> выводит их в одну строку и ставит между ними пробел:</p>'
        + ex('print("Счёт", 3, ":", 1)') +
        '<p>Четыре аргумента — две строки и два числа — оказались в одной строке вывода через пробелы. '
        'Сами запятые в вывод не попадают: они только разделяют аргументы в коде.</p>'
        '<h3>Свой разделитель</h3>'
        '<p>Пробел между значениями можно заменить. Для этого в скобках после значений добавляют [[sep]]="…", '
        'а вместо многоточия в кавычках пишут свой разделитель:</p>'
        + ex('print(27, 10, 2026, sep=".")\nprint("Москва", "Казань", "Сочи", sep=" - ")\nprint("кибер", "спорт", sep="")') +
        '<p>В первой строке вывода числа соединены точками, получилась дата. Во второй между городами дефис с пробелами. '
        'В третьей разделитель пустой, <code>sep=""</code>, и слова слились в одно.</p>'
        '<p>Сам <code>sep</code> на экран не выводится: он только говорит <code>print</code>, чем разделять значения. '
        'Такой аргумент с именем и знаком <code>=</code> называют <b>именованным аргументом</b>. '
        'Его пишут после обычных значений.</p>'
        '<h3>Пустая строка вывода</h3>'
        '<p>Если не передать <code>print</code> ничего, он выведет только переход на новую строку, '
        'и на экране останется пустая строчка. Так делают отступ между частями вывода:</p>'
        + ex('print("Список покупок")\nprint()\nprint("хлеб, молоко, яблоки")') +
        '<p>Между заголовком и списком появилась пустая строка вывода.</p>'
    )
    return th('Несколько значений и sep', terms, body)


