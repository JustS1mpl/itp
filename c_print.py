        'называется [[строка|строкой]]. Это второе значение слова «строка», и оно главное: «строка» в Python — '
        'это текст в кавычках. Когда речь о строчке программы или экрана, будем так и говорить: «строка кода», '
        '«строка вывода».</p>'
        '<p>Строки бывают в двойных и в одинарных [[кавычки|кавычках]] — это одно и то же:</p>'
