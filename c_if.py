def th_elif():
    terms = [
        ('elif',
         '«Иначе если»: следующее условие в цепочке. Проверяется, только если все условия выше оказались ложными. '
         'Из цепочки if / elif / else выполняется ровно один блок — первый подходящий.\n'
         'Пример:\nscore = 75\nif score >= 90:\n    print("A")\nelif score >= 70:\n    print("B")\nelse:\n    print("C")\nВывод:\nB'),
        ('and', 'Логическое «и»: истинно, только если истинны обе части.\nПример:\nage = 15\nprint(age >= 14 and age < 18)\nВывод:\nTrue'),
        ('or', 'Логическое «или»: истинно, если истинна хотя бы одна часть.\nПример:\nday = 6\nprint(day == 6 or day == 7)\nВывод:\nTrue'),
        ('not', 'Логическое «не»: превращает True в False и наоборот.\nПример:\nrain = False\nprint(not rain)\nВывод:\nTrue'),
    ]
    body = (
        '<h3>Несколько вариантов: elif</h3>'
        '<p>Когда вариантов больше двух, между <code>if</code> и <code>else</code> ставят [[elif]] («иначе если»):</p>'
        + ex('score = int(input("Баллы: "))\nif score >= 90:\n    print("Отлично")\nelif score >= 70:\n    print("Хорошо")\n'
             'elif score >= 50:\n    print("Зачёт")\nelse:\n    print("Пересдача")', ['75']) +
        '<p>Python проверяет условия сверху вниз и выполняет только первый подходящий блок, остальные пропускает. '
        'Поэтому 75 даёт «Хорошо», хотя условие 75 ≥ 50 тоже верно. Отсюда правило: в цепочке сначала самое строгое условие. '
        'Если поменять порядок и начать с <code>score &gt;= 50</code>, все от 50 до 100 получат «Зачёт».</p>'
        '<h3>and, or, not</h3>'
        '<p>Условия соединяют логическими операциями: [[and]] — истинно, если верны оба условия; [[or]] — если верно '
        'хотя бы одно; [[not]] — переворачивает значение.</p>'
        + ex('age = 15\nticket = False\nprint(age >= 14 and age < 18)\nprint(age < 14 or ticket)\nprint(not ticket)') +
        '<p>Сначала выполняется <code>not</code>, потом <code>and</code>, потом <code>or</code>; при сомнениях ставь скобки. '
        'Проверка «число в промежутке» короче цепочкой: <code>14 &lt;= age &lt;= 17</code>.</p>'
        + ex('year = int(input("Год: "))\nif (year % 4 == 0 and year % 100 != 0) or year % 400 == 0:\n    print("Високосный")\nelse:\n    print("Обычный")', ['2024']) +
        '<p>Блоки можно вкладывать друг в друга: внутри блока <code>if</code> может стоять ещё один <code>if</code> '
        'со своим, более глубоким отступом. Но часто вложенность заменяется <code>and</code> или <code>elif</code> — так читать проще.</p>'
    )
    return th('elif и логические операции', terms, body)


