def th_match():
    terms = [
        ('условное выражение',
         'Короткий if внутри выражения: ЗНАЧЕНИЕ1 if УСЛОВИЕ else ЗНАЧЕНИЕ2. Даёт первое значение, если условие истинно, иначе второе.\n'
         'Пример:\nn = 7\nprint("чёт" if n % 2 == 0 else "нечет")\nВывод:\nнечет'),
        ('match',
         'Выбор по значению: match ПЕРЕМЕННАЯ: и ниже блоки case ВАРИАНТ:. Выполняется первый совпавший case. '
         'Варианты можно перечислять через |, case _ ловит всё остальное.\n'
         'Пример:\ncmd = "w"\nmatch cmd:\n    case "w" | "вверх":\n        print("Иду вверх")\n    case _:\n        print("Не понял")\n'
         'Вывод:\nИду вверх'),
    ]
    body = (
        '<h3>Условное выражение</h3>'
        '<p>Когда нужно просто выбрать одно из двух значений, полный <code>if</code> на четыре строки — многовато. '
        'Для этого есть [[условное выражение]]: <code>A if условие else B</code>:</p>'
        + ex('n = int(input())\nkind = "чётное" if n % 2 == 0 else "нечётное"\nprint(f"{n} — {kind}")\ncoins = 1\nprint(f"{coins} монет{\'а\' if coins == 1 else \'ы\'}")', ['7']) +
        '<p>Это выражение, а не отдельная команда: его можно положить в переменную или вставить прямо в f-строку.</p>'
        '<h3>match</h3>'
        '<p>Когда переменную сравнивают с длинным списком конкретных значений — команды, пункты меню, — '
        'вместо цепочки <code>elif x == ...</code> удобнее [[match]]:</p>'
        + ex('cmd = input("Команда: ")\nmatch cmd:\n    case "w" | "вверх":\n        print("Иду вверх")\n    case "s" | "вниз":\n'
             '        print("Иду вниз")\n    case "q":\n        print("Выход")\n    case _:\n        print("Не понял команду")', ['вниз']) +
        '<p>Python сверяет значение с вариантами сверху вниз и выполняет первый совпавший <code>case</code>. '
        'Через <code>|</code> перечисляют несколько вариантов, <code>case _</code> — «всё остальное», как <code>else</code>. '
        'Блоки внутри <code>case</code> сдвинуты ещё на один уровень.</p>'
    )
    return th('Условное выражение и match', terms, body)


