def th_count():
    terms = [
        ('setdefault', 'Возвращает значение по ключу, а если ключа нет — сначала добавляет его с указанным значением. '
                       'Удобно для группировки в списки.\nПример:\ng = {}\ng.setdefault("10А", []).append("Ира")\nprint(g)\nВывод:\n{\'10А\': [\'Ира\']}'),
        ('update', 'Добавляет в словарь все пары из другого словаря, совпадающие ключи перезаписывает.\n'
                   'Пример:\nd = {"a": 1}\nd.update({"a": 5, "b": 2})\nprint(d)\nВывод:\n{\'a\': 5, \'b\': 2}'),
    ]
    body = (
        '<h3>Подсчёт</h3>'
        '<p>Самая частая работа со словарём — посчитать, сколько раз встречается каждое значение. Ключ — то, что считаем, '
        'значение — счётчик. <code>get(w, 0)</code> даёт 0 для нового слова:</p>'
        + ex('votes = "Ира Ли Ира Тимур Ира Ли".split()\ncount = {}\nfor v in votes:\n    count[v] = count.get(v, 0) + 1\nprint(count)') +
        '<h3>Группировка</h3>'
        '<p>Если по ключу нужно собрать не число, а список, помогает [[setdefault]]: он возвращает список по ключу, '
        'а если ключа ещё нет — сначала создаёт пустой. [[update]] вливает в словарь другой словарь:</p>'
        + ex('pupils = [("Ира", "10А"), ("Ли", "10Б"), ("Тимур", "10А")]\nby_class = {}\nfor name, cls in pupils:\n'
             '    by_class.setdefault(cls, []).append(name)\nprint(by_class)\nby_class.update({"11А": []})\nprint(list(by_class))') +
        '<h3>Сортировка по значению</h3>'
        '<p><code>sorted(d)</code> сортирует ключи. Чтобы отсортировать по значению — например, по числу голосов, — '
        'пользуются тем, что кортежи сравниваются поэлементно: сначала первые элементы, при равенстве — вторые. '
        'Собираем пары (−голоса, имя) и сортируем: минус даёт порядок по убыванию, а имя решает ничью по алфавиту:</p>'
        + ex('count = {"Ира": 3, "Ли": 2, "Тимур": 1, "Ким": 2}\npairs = []\nfor name, c in count.items():\n    pairs.append((-c, name))\n'
             'for c, name in sorted(pairs):\n    print(name, -c)') +
        '<p>В теме «Гибкие функции» появится способ короче — сортировка с ключом, а пока этот приём работает всегда.</p>'
    )
    return th('Подсчёт и группировка', terms, body)


