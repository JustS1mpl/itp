def th_set():
    terms = [
        ('set',
         'Множество — набор уникальных значений без порядка, в фигурных скобках. Повторы удаляются сами. '
         'Пустое множество — set(), а не {} (это пустой словарь). Проверка in очень быстрая.\n'
         'Порядок элементов у множества не задан, поэтому для вывода его сортируют.\n'
         'Пример:\nprint(sorted(set("банан")))\nprint(len({1, 2, 2, 3}))\nВывод:\n[\'а\', \'б\', \'н\']\n3'),
        ('add', 'Добавляет элемент в множество (если он уже есть — ничего не меняется).\nПример:\ns = {1}\ns.add(2)\ns.add(1)\nprint(s)\nВывод:\n{1, 2}'),
        ('discard', 'Удаляет элемент, если он есть; если нет — ничего не делает (в отличие от remove, который падает с KeyError).\n'
                    'Пример:\ns = {1, 2}\ns.discard(5)\nprint(s)\nВывод:\n{1, 2}'),
    ]
    body = (
        '<p>[[set|Множество]] хранит только уникальные значения — повторы исчезают сами. Порядка у множества нет, '
        'поэтому для вывода его обычно сортируют. Пустое множество создают через <code>set()</code>: '
        '<code>{}</code> — это пустой словарь.</p>'
        + ex('visits = ["Ира", "Ли", "Ира", "Тимур", "Ли"]\nunique = set(visits)\nprint(len(visits), len(unique))\nprint(sorted(unique))\n'
             'tags = set()\ntags.add("python")\ntags.add("python")\ntags.add("игры")\ntags.discard("кино")\nprint(sorted(tags))') +
        '<p>[[add]] добавляет элемент, [[discard]] удаляет — и не падает, если элемента нет (метод <code>remove</code> в этом случае '
        'выдаёт KeyError).</p>'
        '<h3>Операции над множествами</h3>'
        '<p>Множества можно сравнивать как в математике: объединение <code>|</code>, пересечение <code>&amp;</code>, '
        'разность <code>-</code> и «только в одном из двух» <code>^</code>:</p>'
        + ex('ira = {"кино", "футбол", "игры"}\nli = {"игры", "музыка", "кино"}\nprint(sorted(ira | li))\nprint(sorted(ira & li))\n'
             'print(sorted(ira - li))\nprint(sorted(ira ^ li))') +
        '<p>Знак <code>|</code> на компьютере — Shift и обратная косая черта, <code>&amp;</code> — Shift и 7, '
        '<code>^</code> — Shift и 6 в английской раскладке.</p>'
    )
    return th('Множества', terms, body)


