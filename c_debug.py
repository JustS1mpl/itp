# Тема 10 «Поиск ошибок». Ученик знает всё до вложенных циклов включительно.
# Две теории: как читать сообщение об ошибке во время работы (Traceback); логические ошибки — трассировка,
# отладочный print, граничные случаи. Задачи — почти все «исправь».


def th_traceback():
    terms = [
        ('Traceback',
         'Отчёт об ошибке, которая случилась во время работы программы. Читается снизу вверх: последняя строка — тип '
         'ошибки и пояснение, выше — строка кода, где она произошла, её номер (line N) и значки ~ и ^ под проблемным местом.\n'
         'in <module> значит «в основной части программы»; позже, когда появятся свои функции, там будет имя функции.\n'
         'Всё, что программа успела вывести до ошибки, остаётся на экране выше отчёта.'),
    ]
    body = (
        '<p>Ошибки бывают трёх видов. <b>Синтаксические</b> (SyntaxError, IndentationError) Python находит до запуска — '
        'программа не стартует вовсе. <b>Ошибки во время работы</b> случаются на конкретной строке, когда Python пытается '
        'сделать невозможное. <b>Логические</b> ошибки Python не видит вообще: программа работает, но считает не то. '
        'Начнём со второго вида.</p>'
        '<h3>Как читать Traceback</h3>'
        + exerr('prices = "120 45 abc"\ntotal = 0\nfor i in range(3):\n    part = prices.split()[i]\n    print("читаю", part)\n    total += int(part)') +
        '<p>Это [[Traceback]] — отчёт об ошибке. Читай его снизу вверх:</p>'
        '<ol>'
        '<li>Последняя строка — что случилось: <code>ValueError</code>, строку «abc» нельзя превратить в число.</li>'
        '<li>Выше — где: <code>line 6</code> и сама строка кода; значки <code>~</code> и <code>^</code> подчёркивают '
        'выражение, на котором всё сломалось.</li>'
        '<li>Ещё выше — вывод программы до ошибки: два значения прочитались, третье — нет. Это подсказывает, '
        'на какой итерации цикла случилась беда.</li>'
        '</ol>'
        '<p>Запись <code>prices.split()</code> разбивает строку на части по пробелам — подробно её разберём в теме «Списки», '
        'здесь важно только, как читать отчёт.</p>'
        '<h3>Знакомые ошибки</h3>'
        '<table><tr><th>Ошибка</th><th>Что обычно не так</th></tr>'
        '<tr><td>NameError</td><td>опечатка в имени или переменная используется до присваивания</td></tr>'
        '<tr><td>TypeError</td><td>действие с неподходящими типами: строка + число</td></tr>'
        '<tr><td>ValueError</td><td>значение не подходит: int("abc"), int("2.5")</td></tr>'
        '<tr><td>ZeroDivisionError</td><td>деление или остаток на ноль</td></tr>'
        '<tr><td>IndexError</td><td>номер вне строки — часто цикл идёт на один шаг дальше, чем нужно</td></tr>'
        '</table>'
        + exerr('word = "кот"\nfor i in range(len(word) + 1):\n    print(word[i])') +
        '<p>Цикл честно вывел все три буквы и упал на четвёртой итерации: индексы строки — 0, 1, 2, а '
        '<code>range(len(word) + 1)</code> дал ещё и 3. Номер строки и вывод до ошибки вместе сразу указывают на причину.</p>'
    )
    return th('Как читать Traceback', terms, body)


