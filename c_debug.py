def th_logic():
    terms = [
        ('трассировка',
         'Ручное выполнение программы по шагам с таблицей значений переменных после каждой строки или итерации. '
         'Помогает найти место, где значения расходятся с ожидаемыми.'),
        ('отладочный print',
         'Временный print, который выводит значения переменных внутри программы, чтобы увидеть, что она делает на самом деле. '
         'После исправления его убирают.\nПример:\nfor i in range(3):\n    print("i =", i)'),
    ]
    body = (
        '<p>Самые коварные ошибки — логические: программа работает, Python молчит, а ответ неверный. '
        'Вот программа, которая должна считать сумму чисел от 1 до n:</p>'
        + ex('n = 4\ntotal = 0\nfor i in range(1, n):\n    total += i\nprint(total)') +
        '<p>Должно быть 1 + 2 + 3 + 4 = 10, а вышло 6. Найти такую ошибку помогают три приёма.</p>'
        '<h3>1. Трассировка</h3>'
        '<p>[[трассировка|Трассировка]] — выполнить программу вручную, записывая значения переменных после каждой итерации:</p>'
        '<table><tr><th>Итерация</th><th>i</th><th>total</th></tr>'
        '<tr><td>1</td><td>1</td><td>1</td></tr><tr><td>2</td><td>2</td><td>3</td></tr><tr><td>3</td><td>3</td><td>6</td></tr></table>'
        '<p>Итерации с <code>i = 4</code> нет: <code>range(1, n)</code> заканчивается на <code>n - 1</code>. '
        'Нужно <code>range(1, n + 1)</code>. Ошибка «на единицу» — одна из самых частых.</p>'
        '<h3>2. Отладочный print</h3>'
        '<p>Если программа длинная, вручную трассировать долго. Тогда в подозрительное место вставляют '
        '[[отладочный print]] и смотрят, что происходит на самом деле:</p>'
        + ex('count = 0\nfor c in "кокос":\n    count = 0\n    print("отладка:", c, count)\n    if c == "к":\n        count += 1\nprint("Букв к:", count)') +
        '<p>Отладочный вывод сразу показывает: <code>count</code> обнуляется на каждой итерации — строка '
        '<code>count = 0</code> случайно попала внутрь цикла. Накопители и счётчики заводят до цикла. '
        'После исправления отладочные <code>print</code> убирают.</p>'
        '<h3>3. Граничные случаи</h3>'
        '<p>Программа может работать на «обычных» данных и ломаться на краях. Проверяй руками: 0 и 1, отрицательное число, '
        'пустую строку, одно значение вместо многих, самое большое допустимое значение. Именно на них чаще всего '
        'и падают тесты в задачах.</p>'
    )
    return th('Логические ошибки', terms, body)


