             'Первый результат прочитай до цикла и сделай лучшим. В цикле: if s == "стоп": break, иначе сравни int(s) с best.',
             'best = int(input())\nn = 1\nwhile True:\n    s = input()\n    if s == "стоп":\n        break\n    n += 1\n'
             '    if int(s) > best:\n        best = int(s)\nprint(f"Лучший: {best}, попыток: {n}")',
