def th_break():
    terms = [
        ('break',
         'Немедленно завершает цикл: программа продолжается со строки после цикла.\n'
         'Часто используется с while True — циклом, который заканчивается только по break.\n'
         'Пример:\nwhile True:\n    w = input()\n    if w == "стоп":\n        break\n    print(w)'),
    ]
    body = (
        '<p>Иногда удобнее решить, выходить ли из цикла, не в условии, а посреди блока. Для этого есть [[break]] — '
        'он сразу завершает цикл:</p>'
        + ex('n = 1\nwhile n < 100:\n    if n % 7 == 0:\n        break\n    n += 1\nprint("Первое кратное 7:", n)') +
        '<h3>Ввод до стоп-слова</h3>'
        '<p>Частый случай — читать данные, пока не придёт особое значение: «стоп», 0, пустая строка. Цикл пишут как '
        '<code>while True</code> — условие всегда истинно, — а выход делают через <code>break</code>:</p>'
        + ex('total = 0\ncount = 0\nwhile True:\n    price = input("Цена (0 — конец): ")\n    if price == "0":\n        break\n'
             '    total += int(price)\n    count += 1\nprint(f"Покупок: {count}, сумма: {total}")', ['120', '45', '300', '0']) +
        '<p>Проверка стоит сразу после <code>input</code>: стоп-слово не должно попасть в сумму. '
        'Так же ищут максимум: первое значение запоминают как «лучшее», а каждое следующее сравнивают с ним:</p>'
        + ex('best = int(input())\nwhile True:\n    s = input()\n    if s == "стоп":\n        break\n    if int(s) > best:\n        best = int(s)\nprint("Рекорд:", best)',
             ['12', '40', '7', 'стоп']) +
        '<p>В задачах ввод из тестов всегда заканчивается стоп-значением, указанным в условии.</p>'
    )
    return th('break и ввод до стоп-слова', terms, body)


