def th_while():
    terms = [
        ('while',
         'Цикл «пока»: повторяет блок, пока условие истинно. Условие проверяется перед каждым повтором; '
         'если оно сразу ложно, блок не выполнится ни разу.\n'
         'Частая ошибка: забыть изменить переменную в условии — цикл станет бесконечным.\n'
         'Пример:\nn = 3\nwhile n > 0:\n    print(n)\n    n -= 1\nВывод:\n3\n2\n1'),
    ]
    body = (
        '<p>Цикл повторяет действия. [[while]] («пока») повторяет блок, пока условие истинно:</p>'
        + ex('n = 3\nwhile n > 0:\n    print(n)\n    n -= 1\nprint("Старт!")') +
        '<p>Перед каждым повтором Python проверяет условие. Пока <code>n &gt; 0</code>, блок выполняется: вывод и уменьшение '
        '<code>n</code>. Когда <code>n</code> стало 0, условие ложно — цикл закончился, и программа пошла дальше. '
        'Синтаксис как у <code>if</code>: двоеточие и блок с отступом. Один проход по блоку называют <b>итерацией</b>.</p>'
        '<h3>Счётчик и накопитель</h3>'
        '<p>Два частых приёма. <b>Счётчик</b> считает, сколько раз что-то произошло; <b>накопитель</b> собирает сумму. '
        'Оба заводят до цикла и меняют внутри:</p>'
        + ex('total = 0\nday = 0\nwhile total < 1000:\n    day += 1\n    total += 150\nprint(f"Накопил {total} за {day} дн.")') +
        '<p>Копим по 150 в день, пока не наберётся тысяча: цикл не знает заранее, сколько будет повторов, — '
        'это и есть главная сила <code>while</code>.</p>'
        '<h3>Цифры числа</h3>'
        '<p>Число разбирают на цифры с конца: <code>n % 10</code> — последняя цифра, <code>n //= 10</code> — отрезать её. '
        'Повторяем, пока число не кончится:</p>'
        + ex('n = int(input("Число: "))\ns = 0\nwhile n > 0:\n    s += n % 10\n    n //= 10\nprint("Сумма цифр:", s)', ['2048']) +
        '<h3>Бесконечный цикл</h3>'
        '<p>Если условие никогда не станет ложным, цикл не закончится. Обычно это ошибка — например, забыли '
        'изменить переменную. В редакторе такую программу останавливает кнопка «Остановить», '
        'а в задачах проверка прервёт её через 10 секунд.</p>'
    )
    return th('Цикл while', terms, body)


