def th_tuple():
    terms = [
        ('tuple',
         'Кортеж — неизменяемый набор значений в круглых скобках (или просто через запятую). Читать по индексу и срезом можно, '
         'менять нельзя. tuple(x) превращает список или строку в кортеж.\n'
         'Пример:\npoint = (3, 4)\nprint(point[0], len(point))\nВывод:\n3 2'),
        ('enumerate',
         'Перебор с номерами: даёт пары (номер, элемент). Второй аргумент — с какого числа нумеровать.\n'
         'Пример:\nfor i, name in enumerate(["Ира", "Ли"], 1):\n    print(i, name)\nВывод:\n1 Ира\n2 Ли'),
        ('zip',
         'Склеивает несколько списков поэлементно в пары (тройки…). Останавливается на самом коротком.\n'
         'Пример:\nfor n, s in zip(["Ира", "Ли"], [90, 75]):\n    print(n, s)\nВывод:\nИра 90\nЛи 75'),
        ('reversed',
         'Перебор в обратном порядке, исходный список не меняется.\n'
         'Пример:\nfor x in reversed([1, 2, 3]):\n    print(x, end=" ")\nВывод:\n3 2 1'),
    ]
    body = (
        '<h3>Кортежи</h3>'
        '<p>[[tuple|Кортеж]] похож на список, но его нельзя изменить: ни заменить элемент, ни добавить. Пишется в круглых скобках. '
        'Кортежи берут для данных, которые не должны меняться: координаты, дата, цвет.</p>'
        + ex('point = (3, 4)\ncolor = (255, 128, 0)\nprint(point[0], color[-1], len(color))\nprint(color[:2])') +
        '<h3>Распаковка</h3>'
        '<p>Значения из кортежа или списка раскладывают по переменным одной строкой — это <b>распаковка</b>. '
        'Скобки вокруг кортежа можно не писать. Так меняют местами две переменные без третьей:</p>'
        + ex('x, y = (3, 4)\nprint(x, y)\na, b = 1, 2\na, b = b, a\nprint(a, b)\nfirst, last = input("Имя и фамилия: ").split()\nprint(last, first)', ['Ира Ким']) +
        '<p>Число переменных слева должно совпадать с числом значений справа, иначе будет ValueError.</p>'
        '<h3>enumerate, zip, reversed</h3>'
        '<p>Три помощника для циклов. [[enumerate]] даёт номер вместе с элементом, [[zip]] перебирает несколько списков '
        'параллельно, [[reversed]] — в обратном порядке. Распаковка в заголовке цикла раскладывает пары по переменным:</p>'
        + ex('names = ["Ира", "Тимур", "Ли"]\nscores = [90, 75, 88]\nfor i, name in enumerate(names, 1):\n    print(i, name)\n'
             'for name, s in zip(names, scores):\n    print(f"{name}: {s}")\nprint(list(reversed(names)))') +
        '<p>Без <code>enumerate</code> номер пришлось бы считать вручную, без <code>zip</code> — перебирать индексы '
        '<code>range(len(...))</code>. С ними код короче и понятнее.</p>'
    )
    return th('Кортежи, распаковка, enumerate и zip', terms, body)


