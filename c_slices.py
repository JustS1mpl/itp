def th_text():
    terms = [
        ('strip', 'Убирает пробелы и переводы строк по краям строки (lstrip — только слева, rstrip — только справа). '
                  'Можно передать набор символов, которые нужно убрать.\nПример:\nprint("  ок  ".strip() + "!")\nprint("...да!".strip(".!"))\nВывод:\nок!\nда'),
        ('lstrip', 'Убирает пробелы слева.\nПример:\nprint("  ок".lstrip())\nВывод:\nок'),
        ('rstrip', 'Убирает пробелы справа.\nПример:\nprint("ок  ".rstrip() + "|")\nВывод:\nок|'),
        ('replace', 'Возвращает строку, где все вхождения одной подстроки заменены другой. Третий аргумент — сколько замен сделать.\n'
                    'Пример:\nprint("мама мыла".replace("ма", "па"))\nВывод:\nпапа мыла'),
        ('find', 'Индекс первого вхождения подстроки или -1, если её нет. В отличие от index, не падает с ошибкой.\n'
                 'Пример:\nprint("kira@mail.ru".find("@"))\nprint("abc".find("z"))\nВывод:\n4\n-1'),
        ('title', 'Каждое слово с большой буквы, остальные буквы — маленькие.\nПример:\nprint("иванов иван".title())\nВывод:\nИванов Иван'),
        ('zfill', 'Дополняет строку нулями слева до нужной длины.\nПример:\nprint("7".zfill(3))\nВывод:\n007'),
    ]
    body = (
        '<p>Данные от людей почти всегда «грязные»: лишние пробелы, разный регистр, не те символы. Для чистки есть методы строк. '
        'Все они возвращают новую строку — исходная не меняется.</p>'
        + ex('raw = "   иВАНОВА анна  "\nclean = raw.strip().title()\nprint(f"[{clean}]")\nprint("8-916-123".replace("-", ""))\nprint("9".zfill(3))') +
        '<p>[[strip]] срезает пробелы по краям ([[lstrip]] и [[rstrip]] — только с одной стороны); если передать ему строку '
        'символов, он срежет с краёв их: <code>"..да!".strip(".!")</code> — «да». [[title]] делает каждое слово '
        'с большой буквы, [[replace]] заменяет все вхождения подстроки, [[zfill]] дописывает нули слева.</p>'
        '<h3>find: где подстрока</h3>'
        '<p>[[find]] возвращает индекс начала подстроки или <code>-1</code>, если её нет. Вместе со срезом это главный способ '
        'вырезать кусок текста:</p>'
        + ex('email = "kira.pro@mail.ru"\nat = email.find("@")\nprint(at)\nprint(email[:at])\nprint(email[at + 1:])\nprint(email.find("#"))') +
        '<p>Логин — всё до «@», домен — всё после. Если подстроки нет, <code>find</code> вернёт -1, и срез с ним даст '
        'неожиданный результат — поэтому сначала проверяют: <code>if at != -1</code>. У строк есть и метод <code>index</code>, '
        'как у списков, но при отсутствии подстроки он падает с ValueError.</p>'
    )
    return th('Обработка текста', terms, body)


