# Нора после «Запросы к серверам»: асинхронность. Две теории: async/await, asyncio.run, sleep, gather; задачи create_task и
# потоки (threading — объяснение и код для компьютера, в приложении не запускается).
# asyncio.run в движке приложения работает (проверено). Паузы — сотые доли секунды; в тестах времена разные, чтобы порядок
# завершения был однозначным. Время работы не печатаем — оно зависит от машины; печатаем порядок событий и рассчитанные числа.


def th_await():
    terms = [
        ('asyncio', 'Модуль для асинхронных программ: много дел, которые в основном ждут (сеть, файлы, таймеры), идут одновременно.'),
        ('async def', 'Объявляет корутину — функцию, которая умеет вставать на паузу. Её вызов не выполняет тело, а создаёт корутину: '
                      'её нужно дождаться через await или запустить через asyncio.run.'),
        ('await', 'await корутина — дождаться результата. Пока ждём, цикл событий выполняет другие задачи. Пишется только внутри async def.'),
        ('run', 'asyncio.run(main()) — запустить главную корутину и цикл событий; вызывается один раз в программе.'),
        ('sleep', 'asyncio.sleep(секунды) — асинхронная пауза: корутина ждёт, а другие в это время работают. Обычный time.sleep останавливает всё.'),
        ('gather', 'asyncio.gather(к1, к2, …) — выполнить корутины одновременно и вернуть список их результатов в порядке аргументов.'),
    ]
    body = (
        '<p>Многие программы большую часть времени ждут: ответа сервера, загрузки файла, таймера. Если ждать по очереди, три загрузки по '
        'секунде займут три секунды. Асинхронная программа начинает все три, а пока одна ждёт, работают другие, — и всё займёт около '
        'секунды. Для этого есть модуль [[asyncio]].</p>'
        '<p>Функция, которая умеет ждать, объявляется через [[async def]] — это корутина. Внутри неё [[await]] говорит: «здесь подожду, '
        'а пока пусть работают другие». [[sleep]] — асинхронная пауза, ею удобно изображать ожидание. Всё запускает [[run]]:</p>'
        + ex('import asyncio\n\n\nasync def download(name, seconds):\n    print("начал", name)\n    await asyncio.sleep(seconds)\n    print("скачал", name)\n'
             '    return len(name)\n\n\nasync def main():\n    sizes = await asyncio.gather(download("фото", 0.03), download("видео", 0.05), download("текст", 0.01))\n'
             '    print(sizes)\n\n\nasyncio.run(main())') +
        '<p>[[gather]] запустил три загрузки разом: все три «начал» напечатались сразу, а «скачал» — по мере готовности, первым самый '
        'быстрый. Результаты gather возвращает в порядке аргументов, а не завершения. Всё вместе заняло столько, сколько самая долгая '
        'загрузка, — 0,05 секунды, а не 0,09.</p>'
        '<p>Важно: внутри корутин ждут только через await. Обычный <code>time.sleep</code> остановил бы всю программу, и выгоды не было бы.</p>'
    )
    return th('async и await', terms, body)


