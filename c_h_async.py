def th_tasks():
    terms = [
        ('create_task', 'asyncio.create_task(корутина) — запустить корутину в фоне сразу, а дождаться результата потом: await задача.'),
        ('threading', 'Модуль потоков: threading.Thread(target=функция, args=(…)) создаёт поток.'),
        ('Thread', 'threading.Thread(target=функция, args=кортеж) — поток, который выполнит функцию с аргументами.'),
        ('start', 'поток.start() — запустить поток.'),
        ('join', 'поток.join() — дождаться, пока поток закончит.'),
        ('time', 'Модуль времени; time.sleep(секунды) — обычная пауза, которая останавливает поток целиком.'),
        ('поток', 'Отдельная линия выполнения внутри программы (модуль threading). Потоки идут параллельно, но делят общие данные — '
                  'и могут испортить их, если писать одновременно. В браузере ИТП потоки не работают, код — для компьютера.'),
    ]
    body = (
        '<p>gather запускает всё сразу и ждёт всё вместе. Иногда удобнее запустить задачу в фоне и заниматься другим, а результат забрать '
        'позже. Для этого [[create_task]]:</p>'
        + ex('import asyncio\n\n\nasync def cook(dish, t):\n    await asyncio.sleep(t)\n    print("готово:", dish)\n    return dish\n\n\nasync def main():\n'
             '    soup = asyncio.create_task(cook("суп", 0.04))\n    tea = asyncio.create_task(cook("чай", 0.01))\n    print("пока всё варится, режу салат")\n'
             '    await asyncio.sleep(0.02)\n    print("салат готов")\n    print("на столе:", await soup, await tea)\n\n\nasyncio.run(main())') +
        '<p>Задачи начали работать сразу после create_task — чай сварился, пока мы резали салат. <code>await soup</code> дождался супа, '
        'а чай был уже готов, и его await вернул результат мгновенно.</p>'
        '<h3>Потоки</h3>'
        '<p>Асинхронность хороша, когда задачи в основном ждут. Есть и другой способ делать дела одновременно — [[поток]] из модуля '
        'threading. На компьютере это выглядит так (в браузере ИТП потоки не запускаются):</p>'
        '<pre>import threading\nimport time\n\n\ndef work(name):\n    time.sleep(1)\n    print(name, "готов")\n\n\nthreads = [threading.Thread(target=work, args=(n,)) for n in ["A", "B", "C"]]\n'
        'for t in threads:\n    t.start()\nfor t in threads:\n    t.join()\nprint("все потоки закончили")</pre>'
        '<p>Потоки опасны общими данными: если два потока одновременно меняют одну переменную, результат может потеряться. Поэтому в '
        'новых программах для ожидания сети чаще выбирают asyncio, а потоки — когда нужна библиотека, не умеющая async.</p>'
    )
    return th('Фоновые задачи и потоки', terms, body)


