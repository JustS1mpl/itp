             'import asyncio\n\n\nasync def cook(dish, t):\n    await asyncio.sleep(t / 100)\n    print(f"готово: {dish}")\n    return dish\n\n\nasync def main(dishes):\n'
             '    tasks = [asyncio.create_task(cook(d, t)) for d, t in dishes]\n    print("повар ждёт")\n    results = [await t for t in tasks]\n'
