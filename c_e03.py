def tab(head, rows):
    h = '<table><tr>' + ''.join('<th>%s</th>' % E(str(x)) for x in head) + '</tr>'
    for r in rows:
        h += '<tr>' + ''.join('<td>%s</td>' % E(str(x)) for x in r) + '</tr>'
    return h + '</table>'


def clean_stmt(t):
    t = t.replace('В файле приведён', 'Ниже приведён')
    t = re.sub(r'\s*Схема[^.]*?(?:\(images/[^)]*\)|images/\S+?\.png)\.', '', t)
    t = re.sub(r'\s*\[(?:авторская схема|архивный формат, авторская подборка)\]', '', t)
    return t.strip()


def clean(t):
    t = re.sub(r'\s*\((?:images|code)/[^)]*\)', '', t or '')
    t = re.sub(r'\s*\(код ниже[^)]*\)', '', t)
    t = t.replace(' [авторское', '')
    return re.sub(r'\.\.', '.', t).strip()


