def ex_block(code, intro):
    e = EXS[code]
    h = '<h3>Решаем вместе</h3><p>%s</p><p><i>%s</i></p>' % (intro, E(clean_stmt(e['statement'])))
    h += tables_html(code)
    h += '<p><b>Рассуждение.</b></p><ol>' + ''.join('<li>%s</li>' % E(clean(s)) for s in e['steps']) + '</ol>'
    h += '<p><b>Ответ: %s</b></p>' % E(e['answer'])
    return h


def type_html(code):
    t = TY[code]
    exs = [x['id'] for x in t['examples']]
