def th_exit():
    terms = [
        ('else у цикла',
         'Блок else после for или while выполняется, если цикл закончился сам, без break. '
         'Удобен для поиска: «перебрал всё и не нашёл».\n'
         'Пример:\nfor d in range(2, 9):\n    if 9 % d == 0:\n        print("делитель", d)\n        break\nelse:\n    print("делителей нет")\n'
         'Вывод:\nделитель 3'),
    ]
    body = (
        '<h3>break выходит только из одного цикла</h3>'
        '<p><code>break</code> завершает тот цикл, в котором стоит, — внешний продолжит работу. Чтобы остановить оба, '
        'заводят флаг: внутренний цикл ставит его и выходит, внешний проверяет флаг сразу после внутреннего:</p>'
        + ex('target = 20\nfound = False\nfor a in range(1, 10):\n    for b in range(a, 10):\n        if a * b == target:\n'
             '            found = True\n            break\n    if found:\n        break\nprint(f"{a} x {b} = {target}" if found else "Не нашлось")') +
        '<p>После выхода из циклов переменные <code>a</code> и <code>b</code> хранят значения на момент <code>break</code>, '
        'поэтому ответ можно вывести после циклов.</p>'
        '<h3>else у цикла</h3>'
        '<p>У <code>for</code> и <code>while</code> бывает свой <code>else</code>: блок выполняется, если цикл дошёл '
        'до конца сам, а не был прерван <code>break</code>. Это [[else у цикла]] заменяет флаг в задачах вида «найди или скажи, что нет»:</p>'
        + ex('for n in range(10, 30):\n    for d in range(2, int(n ** 0.5) + 1):\n        if n % d == 0:\n            break\n'
             '    else:\n        print(n, end=" ")') +
        '<p>Внутренний цикл ищет делитель. Нашёл — <code>break</code>, и <code>else</code> пропускается. '
        'Не нашёл — <code>else</code> выполняется: число простое. Обрати внимание, что <code>else</code> стоит '
        'на одном уровне с <code>for</code>, а не с <code>if</code>.</p>'
    )
    return th('Выход из циклов и else у цикла', terms, body)


