def th_nested():
    terms = [
        ('вложенный цикл',
         'Цикл внутри другого цикла. На каждую итерацию внешнего внутренний проходит целиком: '
         'при 3 итерациях внешнего и 4 внутреннего тело внутреннего выполнится 12 раз.\n'
         'Пример:\nfor i in range(2):\n    for j in range(3):\n        print(i, j, end=" | ")\nВывод:\n0 0 | 0 1 | 0 2 | 1 0 | 1 1 | 1 2 |'),
    ]
    body = (
        '<p>В блоке цикла может стоять другой цикл — [[вложенный цикл]]. На каждую итерацию внешнего цикла '
        'внутренний проходит полностью:</p>'
        + ex('for row in range(1, 4):\n    for col in range(1, 5):\n        print(row * col, end="\\t")\n    print()') +
        '<p>Внешний цикл перебирает строки таблицы, внутренний — столбцы. <code>end="\\t"</code> ставит табуляцию '
        'между числами, а пустой <code>print()</code> после внутреннего цикла переносит на новую строку — '
        'обрати внимание на его отступ: он внутри внешнего цикла, но вне внутреннего.</p>'
        '<h3>Узоры</h3>'
        '<p>Внутренний цикл может зависеть от переменной внешнего — так рисуют треугольники и лесенки:</p>'
        + ex('n = 4\nfor i in range(1, n + 1):\n    for j in range(i):\n        print("*", end="")\n    print()') +
        '<p>На строке номер <code>i</code> внутренний цикл выполняется <code>i</code> раз. Часто внутренний цикл '
        'можно заменить повтором строки — <code>print("*" * i)</code>, — но вложенные циклы нужны, когда символы '
        'в строке разные, например клетки шахматной доски зависят и от строки, и от столбца:</p>'
        + ex('for i in range(4):\n    for j in range(6):\n        print("#" if (i + j) % 2 == 0 else ".", end="")\n    print()') +
        '<h3>Сколько это работает</h3>'
        '<p>Два вложенных цикла по 1000 итераций — это миллион выполнений тела. Для задач это ещё быстро, '
        'но три вложенных цикла по 1000 — уже миллиард, и программа не уложится в лимит. '
        'Поэтому перед тем как вкладывать цикл, стоит прикинуть число повторов.</p>'
    )
    return th('Цикл в цикле', terms, body)


