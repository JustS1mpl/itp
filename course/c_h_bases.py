from dsl import *

# Нора после «Срезы и кортежи»: системы счисления. Ученик знает // и %, строки, циклы, списки, срезы.
# Две теории: основание и двоичная/восьмеричная/шестнадцатеричная (bin, oct, hex, int с основанием); любое основание до 36.


def th_base():
    terms = [
        ('схема Горнера', 'Перевод записи в число слева направо: n = n * основание + цифра для каждой цифры. Так меньше умножений, '
                          'чем считать каждую степень отдельно.'),
        ('основание', 'Сколько цифр в системе счисления. В десятичной — 10 (0–9), в двоичной — 2 (0 и 1), в шестнадцатеричной — 16 '
                      '(0–9 и A–F). Цифра на месте k (справа, с нуля) весит основание в степени k.'),
        ('bin', 'bin(n) — запись целого числа в двоичной системе, строкой с приставкой 0b.\nПример:\nprint(bin(10), bin(255))\nВывод:\n0b1010 0b11111111'),
        ('oct', 'oct(n) — запись в восьмеричной системе с приставкой 0o.\nПример:\nprint(oct(8), oct(64))\nВывод:\n0o10 0o100'),
        ('hex', 'hex(n) — запись в шестнадцатеричной системе с приставкой 0x, буквы маленькие.\nПример:\nprint(hex(255), hex(4096))\nВывод:\n0xff 0x1000'),
    ]
    body = (
        '<p>Запись 345 значит 3 сотни, 4 десятка и 5 единиц: 3·10² + 4·10¹ + 5·10⁰. Десять — это [[основание]] системы. Но основание '
        'может быть любым: компьютер внутри считает в двоичной системе (основание 2), а программисты часто пишут числа в '
        'шестнадцатеричной (16) — так короче.</p>'
        '<p>Двоичное 1011 — это 1·8 + 0·4 + 1·2 + 1·1 = 11. Перевести в двоичную вручную помогают <code>//</code> и <code>%</code>: '
        'остаток от деления на 2 — последняя цифра, а частное переводим дальше. Цифры получаются с конца:</p>'
        + ex('n = 11\ndigits = ""\nwhile n > 0:\n    digits = str(n % 2) + digits\n    n //= 2\nprint(digits)') +
        '<p>Обратно — слева направо: умножаем накопленное на основание и прибавляем очередную цифру. Этот приём называют [[схема Горнера]]:</p>'
        + ex('s = "1011"\nn = 0\nfor d in s:\n    n = n * 2 + int(d)\nprint(n)') +
        '<h3>Готовые функции</h3>'
        '<p>Для частых систем есть [[bin]], [[oct]] и [[hex]], а обратно переводит <code>int</code> со вторым аргументом — основанием:</p>'
        + ex('print(bin(11), oct(11), hex(255))\nprint(bin(11)[2:])\nprint(int("1011", 2), int("ff", 16), int("17", 8))\nprint(f"{11:b} {255:x} {255:X} {5:08b}")') +
        '<p>Срез <code>[2:]</code> убирает приставку. В f-строке формат <code>b</code> даёт двоичную запись без приставки, <code>x</code> и '
        '<code>X</code> — шестнадцатеричную маленькими или большими буквами, а <code>08b</code> дополняет нулями до 8 знаков — так пишут байты.</p>'
        '<p>Шестнадцатеричная удобна тем, что одна её цифра — ровно 4 двоичные: цвет #FF8800 — это три байта: FF красного, 88 зелёного, 00 синего.</p>'
    )
    return th('Двоичная и шестнадцатеричная', terms, body)


def fl_base():
    return fl('Двоичная и шестнадцатеричная', [
        qo('Что выведет программа?', 'print(int("110", 2) + int("A", 16))', ['120', '1100', 'Ошибка'], '110₂ = 6, A₁₆ = 10, вместе 16.'),
        qo('Что выведет программа?', 'print(bin(6)[2:], f"{6:04b}")', ['0b110 0110', '110 110', '011 0110'], 'Срез убирает 0b; 04b дополняет нулями до 4 знаков.'),
        q('Сколько двоичных цифр заменяет одна шестнадцатеричная?', '4', ['2', '8'], '16 = 2⁴: каждая цифра от 0 до F — ровно 4 бита.'),
    ])


def code_base():
    return ts('Двоичная и шестнадцатеричная', [
        task('На вход подаётся целое n ≥ 0. Переведи его в двоичную систему вручную, делением на 2 (без bin и форматов), и выведи запись. '
             'Второй строкой — «Единиц: K», сколько в записи единиц.',
             'Пока n > 0: digits = str(n % 2) + digits; n //= 2. Ноль — особый случай: запись «0».',
             'n = int(input())\ndigits = ""\nwhile n > 0:\n    digits = str(n % 2) + digits\n    n //= 2\nif digits == "":\n    digits = "0"\nprint(digits)\n'
             'print(f"Единиц: {digits.count(\'1\')}")',
             ['11', '0', '1023', '64']),
        task('Цвет. На вход подаётся цвет в виде «#RRGGBB», например «#FF8800». Выведи «R G B» — три числа от 0 до 255 через пробел, а второй '
             'строкой — «Светлый», если их сумма больше 382, иначе «Тёмный».',
             'Срезы: s[1:3], s[3:5], s[5:7]; число из шестнадцатеричной — int(часть, 16).',
             's = input()\nr, g, b = int(s[1:3], 16), int(s[3:5], 16), int(s[5:7], 16)\nprint(r, g, b)\nprint("Светлый" if r + g + b > 382 else "Тёмный")',
             ['#FF8800', '#000000', '#1e90ff', '#FFFFFF']),
        task('Байты. На вход подаются целые числа от 0 до 255 через пробел. Выведи каждое строкой «ЧИСЛО = ДВОИЧНОЕ = HEX», где двоичное — '
             'ровно 8 знаков с нулями впереди, а HEX — две большие шестнадцатеричные цифры.',
             'Форматы f-строки: f"{n:08b}" и f"{n:02X}".',
             'for n in map(int, input().split()):\n    print(f"{n} = {n:08b} = {n:02X}")',
             ['5 255 128', '0', '10 16 200']),
    ])


def th_any():
    terms = [
        ('любое основание', 'Для основания больше 10 после цифр 0–9 идут буквы A–Z: A = 10, B = 11, …, Z = 35. Поэтому наибольшее основание '
                            'с такими цифрами — 36. int(строка, основание) понимает основания от 2 до 36.'),
    ]
    body = (
        '<p>Алгоритм перевода не зависит от основания: делим на него и берём остатки. Нужна только строка цифр — для основания '
        'до 36 это цифры и латинские буквы. Остаток даёт номер цифры в этой строке — [[любое основание]]:</p>'
        + ex('DIGITS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"\n\nfor n, b in [(255, 16), (255, 2), (2026, 36), (100, 3)]:\n    s = ""\n    m = n\n'
             '    while m > 0:\n        s = DIGITS[m % b] + s\n        m //= b\n    print(n, "в системе", b, "—", s)') +
        '<p>Обратно — снова слева направо: номер цифры в строке DIGITS — её значение, его находит <code>find</code> (для чужого символа он вернёт -1). Цифра, которой нет '
        'в этой системе, — ошибка ввода:</p>'
        + ex('DIGITS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"\n\nfor s, b in [("1JQ", 36), ("ff", 16), ("129", 8)]:\n    n = 0\n    for ch in s.upper():\n'
             '        d = DIGITS.find(ch)\n        if d < 0 or d >= b:\n            n = -1\n            print(f"{s}: цифры {ch} нет в системе с основанием {b}")\n            break\n'
             '        n = n * b + d\n    if n >= 0:\n        print(s, "=", n)') +
        '<p>Встроенный <code>int("1JQ", 36)</code> делает то же самое. Свой перевод нужен, когда цифры другие: например, в «азбуке» '
        'коротких ссылок вместо 36 знаков берут 62 — цифры, маленькие и большие буквы.</p>'
    )
    return th('Любое основание', terms, body)


def fl_any():
    return fl('Любое основание', [
        qo('Что выведет программа?', 'print(int("Z", 36), int("10", 36))', ['35 10', '36 36', 'Ошибка'], 'Z — 35-я цифра; 10₃₆ = 36.'),
        q('Почему у int(строка, основание) основание не больше 36?', 'Цифр 0–9 и букв A–Z всего 36', ['Так решили для скорости', 'Компьютер не умеет больше'],
          '10 цифр + 26 латинских букв.'),
        qo('Что выведет программа?', 'n, s = 7, ""\nwhile n > 0:\n    s = str(n % 3) + s\n    n //= 3\nprint(s)', ['7', '12', '111'], '7 = 2·3 + 1.'),
    ])


def code_any():
    return ts('Любое основание', [
        task('На вход подаются число n ≥ 0 и основание b от 2 до 36 через пробел. Выведи запись n в системе с основанием b (буквы — большие) '
             'и, второй строкой, «Проверка: N» — результат обратного перевода через int.',
             'DIGITS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"; цифры с конца — DIGITS[n % b]. Ноль — «0».',
             'DIGITS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"\nn, b = map(int, input().split())\ns = ""\nm = n\nwhile m > 0:\n    s = DIGITS[m % b] + s\n    m //= b\n'
             'if s == "":\n    s = "0"\nprint(s)\nprint(f"Проверка: {int(s, b)}")',
             ['255 16', '2026 36', '0 7', '100 3']),
        task('На вход подаются строка-число и основание через пробел. Переведи в десятичную своим циклом (без int с основанием): буквы можно '
             'писать любого регистра. Если в строке есть цифра, которой нет в этой системе, выведи «Ошибка: цифры X нет в системе с основанием B», '
             'где X — первая такая цифра большой буквой.',
             'd = DIGITS.find(ch) для ch в s.upper(); если d < 0 или d >= b — ошибка. Иначе n = n * b + d.',
             'DIGITS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"\ns, b = input().split()\nb = int(b)\nn = 0\nbad = ""\nfor ch in s.upper():\n    d = DIGITS.find(ch)\n'
             '    if d < 0 or d >= b:\n        bad = ch\n        break\n    n = n * b + d\nprint(f"Ошибка: цифры {bad} нет в системе с основанием {b}" if bad else n)',
             ['1jq 36', 'ff 16', '129 8', '1012 2']),
        task('Сложение в столбик. На вход подаются основание b (от 2 до 16), затем два числа в этой системе, каждое в отдельной строке. '
             'Сложи их и выведи сумму в той же системе большими буквами (ноль записывается как 0). Через десятичную переводить можно.',
             'Оба числа — int(строка, b), сумма — обычное сложение, обратно — делением на b, как в задаче выше.',
             'DIGITS = "0123456789ABCDEF"\nb = int(input())\ntotal = int(input(), b) + int(input(), b)\ns = ""\nwhile total > 0:\n    s = DIGITS[total % b] + s\n    total //= b\n'
             'print(s or "0")',
             ['2\n1011\n111', '16\nff\n1', '8\n0\n0', '5\n44\n1']),
    ])


def build():
    return topic('Системы счисления: любое основание', 'двоичная, шестнадцатеричная, своё основание', [
        th_base(), fl_base(), code_base(),
        th_any(), fl_any(), code_any(),
    ], opt=True)
