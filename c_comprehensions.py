def th_memory():
    terms = [
        ('is', 'Проверяет, что два имени ссылаются на один и тот же объект (а не просто равны). Для сравнения значений — ==.\n'
               'Пример:\na = [1]\nb = a\nc = [1]\nprint(a is b, a is c, a == c)\nВывод:\nTrue False True'),
        ('id', 'Номер объекта в памяти: у одного объекта он один и тот же.\nПример:\na = [1]\nb = a\nprint(id(a) == id(b))\nВывод:\nTrue'),
        ('copy', 'Модуль copy и функция copy.copy — поверхностная копия: новый внешний список, но вложенные объекты общие. '
                 'У списков то же делает метод a.copy() и срез a[:].\n'
                 'Пример:\nimport copy\na = [1, 2]\nb = copy.copy(a)\nb.append(3)\nprint(a)\nВывод:\n[1, 2]'),
        ('deepcopy', 'copy.deepcopy — полная копия: копируются и все вложенные списки и словари.\n'
                     'Пример:\nimport copy\na = [[1], [2]]\nb = copy.deepcopy(a)\nb[0].append(9)\nprint(a)\nВывод:\n[[1], [2]]'),
    ]
    body = (
        '<p>Переменная — это не коробка со значением, а ярлык на объект в памяти. Присваивание <code>b = a</code> '
        'не копирует список, а вешает на тот же список второй ярлык:</p>'
        + ex('a = [1, 2, 3]\nb = a\nb.append(4)\nprint(a)\nprint(a is b, id(a) == id(b))') +
        '<p>Изменили через <code>b</code> — изменился и <code>a</code>: это один и тот же список. Оператор [[is]] проверяет, '
        'один ли это объект, а [[id]] даёт его номер в памяти. <code>==</code> сравнивает значения: два разных списка '
        'с одинаковыми элементами равны, но не являются одним объектом.</p>'
        '<p>Со строками, числами и кортежами такого не бывает — они неизменяемы: любое «изменение» создаёт новый объект. '
        'Ловушка только у изменяемых: списков, словарей, множеств.</p>'
        '<h3>Функции и списки</h3>'
        '<p>В функцию тоже передаётся ярлык. Если функция меняет список-аргумент, меняется исходный:</p>'
        + ex('def add_bonus(scores):\n    scores.append(100)\n\nmy = [5, 7]\nadd_bonus(my)\nprint(my)') +
        '<p>Иногда это и нужно, но чаще неожиданно. Безопасный стиль — не менять аргумент, а возвращать новый список.</p>'
        '<h3>Копии</h3>'
        '<p>Независимую копию списка дают <code>a.copy()</code>, срез <code>a[:]</code> или [[copy]] из модуля copy. Но это '
        '<b>поверхностная</b> копия: если внутри списки, они остаются общими. Полную копию делает [[deepcopy]]:</p>'
        + ex('import copy\ngrid = [[0, 0], [0, 0]]\nflat = grid.copy()\ndeep = copy.deepcopy(grid)\nflat[0][0] = 1\ndeep[1][1] = 2\nprint(grid)\nprint(deep)') +
        '<p>Список, как и строку, можно умножить на число: <code>[0] * 3</code> — это <code>[0, 0, 0]</code>. '
        'Отсюда похожая ловушка — список списков через умножение:<code>&#91;[0] * 3] * 3</code> создаёт три ярлыка на одну и ту же строку. '
        'Правильно — списочным выражением: <code>&#91;[0] * 3 for i in range(3)]</code>.</p>'
        + ex('bad = [[0] * 3] * 3\nbad[0][0] = 1\nprint(bad)\ngood = [[0] * 3 for i in range(3)]\ngood[0][0] = 1\nprint(good)')
        + '<h3>Сравнение с None</h3>'
        '<p>None в программе ровно один, поэтому с ним сравнивают через <code>is</code>: <code>x is None</code>, <code>x is not None</code>. '
        'Так принято: это короче проверки ==, и никакой хитрый объект не сможет «притвориться» равным None:</p>'
        + ex('ages = {"Аня": 15}\nage = ages.get("Борис")\nprint(age is None, ages.get("Аня") is not None)')
    )
    return th('Имена и объекты', terms, body)


