def th_listcomp():
    terms = [
        ('списочное выражение',
         'Короткая запись создания списка: [выражение for x in набор if условие]. Условие необязательно.\n'
         'Пример:\nprint([x * x for x in range(1, 6) if x % 2 == 1])\nВывод:\n[1, 9, 25]'),
        ('словарное выражение', 'То же для словаря: {ключ: значение for x in набор}.\nПример:\nprint({w: len(w) for w in ["кот", "ёж"]})\nВывод:\n{\'кот\': 3, \'ёж\': 2}'),
        ('множественное выражение', 'То же для множества: {выражение for x in набор}. Повторы отбрасываются.\n'
                                    '«ё» стоит в таблице кодов отдельно, после «я», поэтому при сортировке оказывается в конце.\n'
                                    'Пример:\nprint(sorted({w[0] for w in ["кот", "кит", "ёж"]}))\nВывод:\n[\'к\', \'ё\']'),
    ]
    body = (
        '<p>Частая задача — сделать из одного списка другой: квадраты чисел, длины слов, только положительные. '
        'Обычно это цикл с <code>append</code>, но есть короткая запись — [[списочное выражение]]:</p>'
        + ex('nums = [3, -1, 4, -5, 2]\nsquares = []\nfor x in nums:\n    squares.append(x * x)\nprint(squares)\nprint([x * x for x in nums])\nprint([x for x in nums if x > 0])') +
        '<p>Читается почти по-русски: «x в квадрате для каждого x из nums». Условие <code>if</code> в конце отбирает элементы. '
        'Если нужно не отбросить, а заменить, условное выражение ставят в начало:</p>'
        + ex('nums = [3, -1, 4, -5, 2]\nprint([x if x > 0 else 0 for x in nums])\nwords = "Python это просто".split()\nprint([w.upper() for w in words if len(w) > 3])') +
        '<h3>Словари и множества</h3>'
        '<p>Так же создают [[словарное выражение|словари]] — пара <code>ключ: значение</code> в фигурных скобках — '
        'и [[множественное выражение|множества]]:</p>'
        + ex('words = ["кот", "жираф", "ёж", "кит"]\nprint({w: len(w) for w in words})\nprint(sorted({w[0] for w in words}))') +
        '<h3>Вложенные</h3>'
        '<p>Внутри выражения может быть другое — так получают таблицы, то есть списки списков:</p>'
        + ex('table = [[i * j for j in range(1, 4)] for i in range(1, 4)]\nprint(table)\nprint(table[1][2])') +
        '<p><code>table[1][2]</code> — сначала строка с индексом 1, в ней элемент с индексом 2. Если выражение получается '
        'длиннее строки и трудно читается, лучше вернуться к обычному циклу.</p>'
    )
    return th('Списочные выражения', terms, body)


