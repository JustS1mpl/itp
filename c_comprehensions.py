def th_genexp():
    terms = [
        ('выражение-генератор',
         'Как списочное выражение, но в круглых скобках: значения создаются по одному по мере перебора и не хранятся списком. '
         'Внутри вызова функции свои скобки можно не писать: sum(x for x in ...).\n'
         'Пример:\nprint(sum(x * x for x in range(4)))\nВывод:\n14'),
        ('any', 'True, если хотя бы один элемент истинен (или условие выполнено хотя бы раз).\nПример:\nprint(any(c.isdigit() for c in "kira7"))\nВывод:\nTrue'),
        ('all', 'True, если все элементы истинны. Для пустого набора — True.\nПример:\nprint(all(x > 0 for x in [3, 5, -1]))\nВывод:\nFalse'),
    ]
    body = (
        '<p>Если результат нужен только чтобы сразу его посчитать — сумму, максимум, — список можно не создавать. '
        '[[выражение-генератор|Выражение-генератор]] записывается как списочное, но в круглых скобках и выдаёт значения по одному. '
        'Внутри вызова функции хватает её собственных скобок:</p>'
        + ex('print(sum(x * x for x in range(1, 101)))\nwords = "кот жираф ёж".split()\nprint(max(len(w) for w in words))\ns = "2048"\nprint(sum(int(c) for c in s))') +
        '<p>Для миллиона чисел список занял бы память под миллион элементов, а генератор держит в памяти одно текущее значение.</p>'
        '<h3>any и all</h3>'
        '<p>[[any]] отвечает, есть ли хоть один подходящий элемент, [[all]] — все ли подходят. С генератором это проверка '
        'в одну строку вместо цикла с флагом:</p>'
        + ex('pwd = "Kira2010"\nprint(any(c.isdigit() for c in pwd))\nprint(any(c.isupper() for c in pwd))\nmarks = [5, 4, 3, 5]\n'
             'print(all(m >= 3 for m in marks))\nprint(all(m == 5 for m in marks))') +
        '<p>Как и <code>and</code>/<code>or</code>, они останавливаются, как только ответ ясен: <code>any</code> — на первом '
        'подходящем, <code>all</code> — на первом неподходящем.</p>'
    )
    return th('Генераторы, any и all', terms, body)


