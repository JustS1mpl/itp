def alg(code):
    out = []
    for s in TY[code]['algorithm_steps']:
        a, b = s.split(': ', 1) if ': ' in s else ('', s)
        out.append('<li><b>%s.</b> %s</li>' % (E(a), E(b)) if a else '<li>%s</li>' % E(b))
    return '<ol>' + ''.join(out) + '</ol>'


