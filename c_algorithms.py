def th_binary():
    terms = [
        ('бинарный поиск', 'Поиск в отсортированном списке делением пополам: смотрим середину и отбрасываем ту половину, где искомого '
                           'быть не может. На миллионе элементов — около 20 шагов. На неотсортированном списке ошибается.'),
        ('bisect', 'Модуль с бинарным поиском для отсортированных списков: bisect_left, insort и другие.'),
        ('bisect_left', 'bisect.bisect_left(a, x) — номер, куда вставить x в отсортированный список a, чтобы порядок не нарушился: '
                        'номер первого элемента, который не меньше x (или len(a)).\n'
                        'Пример:\nimport bisect\na = [10, 20, 30, 40]\nprint(bisect.bisect_left(a, 25), bisect.bisect_left(a, 30), bisect.bisect_left(a, 99))\n'
                        'Вывод:\n2 2 4'),
        ('insort', 'bisect.insort(a, x) — вставляет x в отсортированный список a на своё место, сохраняя порядок.\n'
                   'Пример:\nimport bisect\na = [10, 20, 30]\nbisect.insort(a, 25)\nprint(a)\nВывод:\n[10, 20, 25, 30]'),
    ]
    body = (
        '<p>Если список <b>отсортирован</b>, искать можно гораздо быстрее — как в игре «угадай число от 1 до 100»: называешь середину, '
        'слышишь «больше» или «меньше» и сразу отбрасываешь половину вариантов. Это [[бинарный поиск]].</p>'
        + ex('def binary_steps(a, x):\n    lo, hi = 0, len(a) - 1\n    steps = 0\n    while lo <= hi:\n        steps += 1\n        mid = (lo + hi) // 2\n'
             '        if a[mid] == x:\n            return mid, steps\n        if a[mid] < x:\n            lo = mid + 1\n        else:\n            hi = mid - 1\n'
             '    return -1, steps\n\n\nnums = list(range(1, 1000001))\nprint(binary_steps(nums, 999999))\nprint(binary_steps(nums, -5))') +
        '<p><code>lo</code> и <code>hi</code> — границы отрезка, где ещё может быть ответ. Каждый шаг сравнивает середину с искомым '
        'и сдвигает одну из границ за середину. Когда <code>lo</code> обгоняет <code>hi</code>, отрезок пуст — элемента нет.</p>'
        '<p>Линейному поиску на тот же миллион нужно до миллиона сравнений, бинарному — 20. Каждый шаг делит отрезок пополам, '
        'поэтому список в 1000 раз длиннее добавляет всего около 10 шагов. Плата за скорость — список обязан быть отсортирован, '
        'иначе отброшенная половина может содержать ответ.</p>'
        '<h3>Модуль bisect</h3>'
        '<p>Писать бинарный поиск каждый раз не нужно: в модуле [[bisect]] есть готовый. [[bisect_left]] возвращает место, '
        'куда встал бы элемент, — номер первого элемента, который не меньше искомого. Чтобы узнать, есть ли элемент, '
        'проверяют, что этот номер в пределах списка и там лежит он сам:</p>'
        + ex('import bisect\n\nprices = [99, 150, 150, 300, 450]\ni = bisect.bisect_left(prices, 150)\nprint(i, i < len(prices) and prices[i] == 150)\n'
             'j = bisect.bisect_left(prices, 200)\nprint(j, j < len(prices) and prices[j] == 200)') +
        '<p>[[insort]] вставляет элемент на своё место, и список остаётся отсортированным — не нужно пересортировывать его '
        'после каждого добавления:</p>'
        + ex('import bisect\n\nscores = []\nfor s in [70, 45, 90, 60]:\n    bisect.insort(scores, s)\n    print(scores)')
    )
    return th('Бинарный поиск', terms, body)


