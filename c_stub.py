from dsl import *

# Временная заглушка на время переработки (фаза 0): нужна, чтобы сборка и тесты работали,
# пока новых тем нет. В фазе 3 её заменит настоящий курс.


def build_intro():
    body = ('<p>Курс полностью пишется заново. Здесь пока одна пробная тема, '
            'чтобы приложение собиралось и открывалось.</p>')
    return topic('Знакомство', 'временная заглушка', [
        th('Что здесь будет', [], body),
        fl('Проверка', [q('Что сейчас происходит с курсом?', 'Его пишут заново', ['Он закончен', 'Его удалили навсегда'],
                          'Темы появятся по мере работы над новой версией.')]),
    ], intro=True)


def build():
    terms = [('print', 'Функция print показывает на экране то, что ей передали в скобках.\n'
                       'Пример:\nprint("Привет")\nВывод:\nПривет')]
    body = ('<p>Программа — это список команд для компьютера. Команда [[print|print]] выводит текст на экран:</p>'
            + ex('print("Сборка работает")')
            + '<p>Текст в кавычках появился в выводе без кавычек.</p>')
    return topic('Пробная тема', 'print', [
        th('Первая команда', terms, body),
        fl('Проверка', [qo('Что выведет программа?', 'print("ок")', ['"ок"', 'print("ок")'],
                           'Кавычки только отмечают текст, на экран они не попадают.')]),
        ts('Задание', [task('Выведи на экран слово <code>готово</code>.',
                            'Используй print и поставь слово в кавычки: print("...").',
                            'print("готово")', [''])]),
    ])
