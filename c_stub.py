from dsl import *

# Временная заглушка на время переработки: нужна, чтобы сборка и проверки работали,
# пока новых тем нет. В фазе 3 её заменят настоящие темы «Знакомство» и «Первая программа».


def build_intro():
    body = ('<p>Курс полностью пишется заново. Здесь пока одна пробная тема, '
            'чтобы приложение собиралось и открывалось.</p>')
    return topic('Знакомство', 'как устроено приложение и как запускать код', [
        th('Что здесь будет', [], body),
    ], intro=True)


def build():
    terms = [
        ('print', 'Функция print показывает на экране то, что ей передали в скобках.\n'
                  'Пример:\nprint("Привет")\nВывод:\nПривет'),
        ('#', 'Знак # начинает комментарий: всё после него до конца строки Python пропускает.\n'
              'Пример:\nprint("да")  # это пояснение\nВывод:\nда'),
        ('SyntaxError', 'Ошибка синтаксиса: Python не понял запись программы, например не закрыта кавычка.'),
        ('NameError', 'Ошибка имени: в программе встретилось слово, которого Python не знает.'),
    ]
    body = ('<p>Программа — это список команд для компьютера. Команда [[print]] выводит текст на экран:</p>'
            + ex('print("Сборка работает")  # пояснение для человека')
            + '<p>Текст в кавычках появился в выводе без кавычек. Всё после [[#]] — комментарий. '
              'Если ошибиться в записи, будет [[SyntaxError]], а если в имени команды — [[NameError]].</p>')
    return topic('Первая программа', 'print, кавычки, sep, end, комментарии', [
        th('Команда print', terms, body),
        fl('Команда print', [qo('Что выведет программа?', 'print("ок")', ['"ок"', 'print("ок")'],
                                'Кавычки только отмечают текст, на экран они не попадают.')]),
        ts('Задачи: разминка', [task('Выведи на экран слово <code>готово</code>.',
                                     'Используй print и поставь слово в кавычки: print("...").',
                                     'print("готово")', [''])]),
    ])
