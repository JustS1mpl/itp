from dsl import *

# Нора после «Циклы в циклах»: черепаха (учебный turtle из v5/py/turtle_shim.py рисует на холсте в приложении).
# Две теории: движение и перо; цвет, заливка и узоры циклами.
# Рисунок в задачах проверяет «хвост» CHECK: он считает нарисованные линии (перо опущено), их общую длину, цвета пера
# и число заливок — так засчитывается любой правильный способ нарисовать фигуру. Ученик видит итог в примере задачи.

CHECK = ('import turtle\n_n, _len, _cols, _fills = 0, 0, "", 0\nfor _o in turtle._LOG:\n    if _o[0] == 0 and _o[5]:\n        _n += 1\n'
         '        _len += ((_o[3] - _o[1]) ** 2 + (_o[4] - _o[2]) ** 2) ** 0.5\n        if _o[6] not in _cols:\n'
         '            _cols = _cols + " " + _o[6] if _cols else _o[6]\n'
         '    if _o[0] == 3:\n        _fills += 1\nprint(f"линий: {_n}, длина: {round(_len)}, цвета: {_cols if _cols else \'нет\'}, заливок: {_fills}")')

NOTE = ' Рисунок проверяется по итогу: сколько линий нарисовано, их общая длина, цвета пера и сколько заливок — этот итог видно в примере.'


def th_move():
    terms = [
        ('turtle', 'Модуль «черепаха»: черепашка ползает по холсту и рисует хвостом-пером. В ИТП рисунок появляется под выводом программы.'),
        ('forward', 'turtle.forward(n) — проползти n шагов вперёд (по направлению взгляда), рисуя линию, если перо опущено. backward — назад.'),
        ('backward', 'turtle.backward(n) — проползти n шагов назад, не поворачиваясь.'),
        ('left', 'turtle.left(угол) — повернуть налево на угол в градусах. right — направо.'),
        ('right', 'turtle.right(угол) — повернуть направо на угол в градусах.'),
        ('penup', 'turtle.penup() — поднять перо: черепашка двигается, не рисуя. pendown() — опустить и рисовать снова.'),
        ('pendown', 'turtle.pendown() — опустить перо: дальше движение рисует линию.'),
        ('goto', 'turtle.goto(x, y) — переползти в точку (x, y) по прямой. Центр холста — (0, 0), y растёт вверх.'),
        ('pensize', 'turtle.pensize(n) — толщина линии.'),
    ]
    body = (
        '<p>Модуль [[turtle]] — маленькая черепашка с пером. Она смотрит вправо и стоит в центре холста. [[forward]] двигает её вперёд, '
        '[[left]] и [[right]] поворачивают на угол в градусах — и за ней остаётся линия:</p>'
        + tu('import turtle\n\nfor _ in range(4):\n    turtle.forward(100)\n    turtle.left(90)') +
        '<p>Квадрат — четыре раза «вперёд и налево на 90». Переменная цикла здесь не нужна, поэтому её назвали <code>_</code> — '
        'это обычное имя, так принято называть счётчик, который внутри цикла не используется. Для правильного многоугольника с n сторонами черепашка в сумме '
        'поворачивается на 360°, значит, на каждом углу — на 360 / n:</p>'
        + tu('import turtle\n\nn = 6\nfor _ in range(n):\n    turtle.forward(70)\n    turtle.left(360 / n)') +
        '<h3>Перо и координаты</h3>'
        '<p>[[penup]] поднимает перо — черепашка переползает, не рисуя, [[pendown]] опускает его снова. [[goto]] ведёт черепашку в точку '
        'по координатам: центр — (0, 0), x растёт вправо, y — вверх. [[backward]] — шаг назад, [[pensize]] — толщина линии:</p>'
        + tu('import turtle\n\nturtle.pensize(3)\nfor i in range(5):\n    turtle.penup()\n    turtle.goto(-100, 60 - i * 30)\n    turtle.pendown()\n'
             '    turtle.forward(40 + i * 30)') +
        '<p>Так рисуют пунктир, столбики диаграмм и отдельные фигуры в разных местах холста.</p>'
    )
    return th('Движение и перо', terms, body)


