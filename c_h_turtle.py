def code_color():
    return ts('Цвет и узоры', [
        task('Флажок. На вход подаются цвет (по-английски, например red) и размер a, каждое в своей строке. Нарисуй закрашенный квадрат со стороной a этим цветом (перо '
             'и заливка — один цвет), каждую сторону одним движением.' + NOTE,
             'turtle.color(c); turtle.begin_fill(); квадрат; turtle.end_fill().',
             'import turtle\n\nc = input()\na = int(input())\nturtle.color(c)\nturtle.begin_fill()\nfor _ in range(4):\n    turtle.forward(a)\n    turtle.left(90)\nturtle.end_fill()',
             ['red\n80', 'blue\n120', 'gold\n50'], tail=CHECK, ex_='Вход:\nred\n80\nВывод:\nлиний: 4, длина: 320, цвета: #ff0000, заливок: 1'),
        task('Розетка. На вход подаются число квадратов n и сторона a, каждое в своей строке. Нарисуй n квадратов со стороной a, каждый следующий повёрнут относительно '
             'предыдущего на 360 / n градусов, чтобы вместе они образовали полный круг. Стороны — одним движением.' + NOTE,
             'Внешний цикл n раз: внутри квадрат (4 раза forward и left(90)), затем turtle.left(360 / n).',
             'import turtle\n\nn = int(input())\na = int(input())\nfor _ in range(n):\n    for _ in range(4):\n        turtle.forward(a)\n        turtle.left(90)\n    turtle.left(360 / n)',
             ['6\n50', '1\n100', '12\n40'], tail=CHECK, ex_='Вход:\n6\n50\nВывод:\nлиний: 24, длина: 1200, цвета: #000000, заливок: 0'),
    ])


def build():
    return topic('Черепаха: рисуем кодом', 'движение, перо, цвет, узоры', [
        th_move(), fl_move(), code_move(),
        th_color(), fl_color(), code_color(),
    ], opt=True)
